import {createHash} from "node:crypto";
import {mkdirSync, readFileSync, writeFileSync} from "node:fs";
import {join, dirname} from "node:path";
import {homedir} from "node:os";
import {fileURLToPath} from "node:url";
import {ensurePrivateReaderDirectory} from "./page-reader-security.mjs";
if (process.platform !== "darwin") throw Error("Page Reader currently supports macOS Chrome.");
const extension = fileURLToPath(new URL("../assets/page-reader/", import.meta.url));
const {key} = JSON.parse(readFileSync(join(extension, "manifest.json")));
const id = createHash("sha256").update(Buffer.from(key, "base64")).digest("hex").slice(0, 32).replace(/./g, n => String.fromCharCode(97 + parseInt(n, 16)));
const path = join(homedir(), ".pi-harness-reader", "launch");
ensurePrivateReaderDirectory(dirname(path));
const quote = s => "'" + s.replaceAll("'", "'\\''") + "'";
writeFileSync(path, "#!/bin/sh\nexec " + [process.execPath, fileURLToPath(new URL("./page-reader-host.mjs", import.meta.url))].map(quote).join(" ") + '\n', {mode: 0o700});
const nativeDir = join(homedir(), "Library/Application Support/Google/Chrome/NativeMessagingHosts");
mkdirSync(nativeDir, {recursive: true});
const name = "com.pi_harness.page_reader";
writeFileSync(join(nativeDir, name + ".json"), JSON.stringify({name, description: "pi Page Reader", path, type: "stdio", allowed_origins: ["chrome-extension://" + id + "/"]}), {mode: 0o600});
console.log("在 chrome://extensions 开启开发者模式，点击「加载已解压的扩展程序」，选择目录：\n" + extension);
