/** Native skill requests must remain editable user turns, including frozen attachments. */
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync, realpathSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { loadOmpTestModule, ompTestRoot } from './lib/omp-runtime-location.mjs';
import { listenIsolated } from './lib/isolated-server.mjs';
import { scrubHostEnv } from './lib/test-env.mjs';
scrubHostEnv();
for (const key of Object.keys(process.env)) if (/API_KEY|TOKEN|SECRET|PASSWORD|^ANTHROPIC_|^OPENAI_/.test(key)) delete process.env[key];
const { OmpClientSession } = await loadOmpTestModule('chat-service.js');
const { ClientStateStore } = await import(pathToFileURL(join(ompTestRoot, 'dist/server/client-state.js')).href);
const root = realpathSync(mkdtempSync(join(tmpdir(), 'omp-skill-history-'))), agent = join(root, 'omp/agent');
const skillDir = join(agent, 'skills', 'fixture');
mkdirSync(skillDir, { recursive: true });
const skillBody = 'NATIVE_SKILL_BODY\n'.repeat(200);
writeFileSync(join(skillDir, 'SKILL.md'), '---\nname: fixture\ndescription: History fixture\n---\n' + skillBody);
const requests = [], events = [];
let client;
const provider = createServer(async (req, res) => {
	let raw = ''; for await (const part of req) raw += part;
	const payload = JSON.parse(raw); if (payload.tools?.length) requests.push(payload);
	res.writeHead(200, { 'content-type': 'text/event-stream' });
	const emit = (type, data) => res.write(`event: ${type}\ndata: ${JSON.stringify({ type, ...data })}\n\n`);
	emit('message_start', { message: { id: `m${requests.length}`, type: 'message', role: 'assistant', model: 'fixture', content: [], usage: { input_tokens: 100, output_tokens: 0 } } });
	emit('content_block_start', { index: 0, content_block: { type: 'text', text: '' } });
	emit('content_block_delta', { index: 0, delta: { type: 'text_delta', text: 'Native skill history reply.' } });
	emit('content_block_stop', { index: 0 });
	emit('message_delta', { delta: { stop_reason: 'end_turn' }, usage: { output_tokens: 12 } });
	emit('message_stop', {}); res.end();
});
const wait = async (test, label) => { for (let i = 0; i < 1000; i++) { if (test()) return; await new Promise(r => setTimeout(r, 20)); } throw Error(`Timed out ${label}`); };
const settled = async () => { await wait(() => !client.session.state.running, 'native reply'); await client.session.refresh(); };
const start = async (selectModel = false) => {
	client = new OmpClientSession('skills', root, new ClientStateStore(join(root, 'client-state.json')));
	client.attachSink(event => events.push(event), false);
	await client.initialize(); if (selectModel) await client.setModel('fixture/fixture');
};
const userText = message => message.questionText ?? message.content.filter(block => block.type === 'text').map(block => block.text).join('\n');
try {
	const port = await listenIsolated(provider);
	writeFileSync(join(agent, 'models.yml'), JSON.stringify({ providers: { fixture: { api: 'anthropic-messages', baseUrl: `http://127.0.0.1:${port}`, apiKey: 'fixture', models: [{ id: 'fixture', input: ['text'], contextWindow: 1000000 }] } } }));
	writeFileSync(join(agent, 'config.yml'), JSON.stringify({ skills: { enabled: true, enableAgentsUser: false, enableAgentsProject: false, enablePiUser: false, enablePiProject: false, enableClaudeUser: false, enableClaudeProject: false, enableCodexUser: false, customDirectories: [join(agent, 'skills')] }, retry: { enabled: false }, compaction: { enabled: false }, cacheWarming: { enabled: false } }));
	await start(true);
	const question = '/skill:fixture Inspect "a  b" exactly';
	const file = join(root, 'source.txt'), draft = 'FROZEN_SKILL_DRAFT\n' + 'x'.repeat(210000) + '\nEND_OF_FROZEN_SKILL_DRAFT';
	writeFileSync(file, 'ORIGINAL_SKILL_FILE');
	await client.prompt(question, [{ path: file, mode: 'inline' }, { path: file, mode: 'inline', editorSnapshot: { cwd: root, text: draft, dirty: true } }]);
	await settled();
	const savedSkill = (await client.session.command('get_entries')).data.entries.find(entry => entry.type === 'custom_message' && entry.customType === 'skill-prompt');
	assert.equal(savedSkill?.attribution, 'user', 'native skill request is persisted before UI projection');
	assert(savedSkill.details.prompt.startsWith(question));
	let user = client.session.state.messages.find(message => message.role === 'user' && userText(message) === question);
	assert(user?.entryId, 'a native skill invocation must have an editable user entry');
	assert.equal(user.userAttachments.length, 2);
	assert.equal(user.userAttachments[0].preview, 'ORIGINAL_SKILL_FILE');
	assert(user.userAttachments.every(attachment => attachment.preview.length <= 12000));
	const originalId = user.entryId, originalFile = client.session.state.sessionFile;
	const native = (await client.session.command('get_entries')).data.entries.find(entry => entry.id === originalId);
	assert.equal(native.type, 'custom_message'); assert.equal(native.customType, 'skill-prompt'); assert.equal(native.attribution, 'user');
	assert(JSON.stringify(requests.at(-1)).includes('NATIVE_SKILL_BODY'));
	await client.handle({ type: 'tree_get', conversationId: client.conversationId, reqId: 'skills-only', filter: 'user-only' });
	assert(events.find(event => event.type === 'tree' && event.reqId === 'skills-only')?.nodes.some(node => node.id === originalId && node.kind === 'user'), 'user-only tree includes native skill turns');
	await client.dispose();
	const savedBytes = readFileSync(originalFile);
	await start(); await client.session.refresh();
	assert.deepEqual(readFileSync(originalFile), savedBytes, 'restoring skill projection does not rewrite native history');
	assert.equal(requests.length, 1, 'restore never invokes a model');
	user = client.session.state.messages.find(message => message.entryId === originalId);
	assert.equal(userText(user), question); assert.equal(user.userAttachments.length, 2);
	rmSync(file);
	const edited = 'Please /skill:fixture inspect the frozen files again';
	await client.handle({ type: 'edit_message', conversationId: client.conversationId, entryId: originalId, text: edited, attachments: user.userAttachments.map(attachment => ({ nativeRef: attachment.nativeRef })) });
	await settled();
	assert.equal(requests.length, 2, 'editing the skill dispatches exactly one new request');
	const sent = JSON.stringify(requests.at(-1).messages);
	assert(sent.includes('NATIVE_SKILL_BODY')); assert(sent.includes('ORIGINAL_SKILL_FILE')); assert(sent.includes('END_OF_FROZEN_SKILL_DRAFT'));
	assert.equal(client.session.state.sessionFile, originalFile);
	assert((await client.session.command('get_entries')).data.entries.some(entry => entry.id === originalId), 'original skill branch is retained');
	const editedUser = client.session.state.messages.find(message => message.role === 'user' && userText(message) === edited);
	assert(editedUser?.entryId, 'inline skill tokens restore the exact submitted draft');
	const nativeDraft = (await client.session.command('navigate_tree', { entryId: editedUser.entryId, summarize: false })).data.editorText;
	assert(nativeDraft.startsWith(edited + '\n\n'), 'UI draft agrees with native rewind for inline skill syntax');
	assert(nativeDraft.includes('END_OF_FROZEN_SKILL_DRAFT')); assert(!nativeDraft.includes('NATIVE_SKILL_BODY'));
	assert.equal(requests.length, 2, 'native rewind does not invoke the model');
	const beforeForeign = requests.length;
	await client.newChat();
	await client.prompt('Foreign skill attachment', [{ nativeRef: user.userAttachments[0].nativeRef }], undefined, 'foreign-skill');
	assert(events.some(event => event.type === 'prompt_result' && event.requestId === 'foreign-skill' && event.receipt === 'rejected'));
	assert.equal(requests.length, beforeForeign, 'a different conversation cannot restore skill attachments');
	console.log('PASS OMP native skill history: user projection, native entry identity, tree filter, restart without transcript rewrite, inline invocation edit and full frozen attachments');
} finally {
	await client?.dispose(); provider.closeAllConnections(); await new Promise(resolve => provider.close(resolve)); rmSync(root, { recursive: true, force: true });
}
