import { createPrivateKey, generateKeyPairSync } from "node:crypto";
import ssh2 from "ssh2";
const { utils } = ssh2;
import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync, mkdirSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { startMockSsh } from "./lib/mock-ssh.mjs";
import { NodeWorkbench } from "../dist/server/node-workbench.js";
import { XshellCredentials } from "../dist/server/xshell-credentials.js";
import { PluginSecrets } from "../dist/server/plugin-facilities.js";

const dataDir = mkdtempSync(join(tmpdir(), "pi-node-test-"));
const port = 8938;
const privateKey = generateKeyPairSync("rsa", { modulusLength: 2048 }).privateKey.export({ type: "pkcs1", format: "pem" });
const mock = await startMockSsh(process.cwd(), port, [utils.parseKey(privateKey)]);
const cryptoFixture = JSON.parse(readFileSync(new URL("./fixtures/xshell7-credentials.json", import.meta.url), "utf8"));
const service = new NodeWorkbench(dataDir, new XshellCredentials(async () => cryptoFixture.identity));
const events = [];
const detach = service.attach("client-a", (event) => events.push(event));
async function call(action, nodeId, payload = {}, terminalId, conversationId) {
	const requestId = crypto.randomUUID();
	await service.handle("client-a", { type: "node_request", requestId, action, nodeId, terminalId, conversationId, payload });
	const response = events.findLast((e) => e.requestId === requestId && (e.event === "result" || e.event === "failure"));
	assert(response, `${action}: missing response`);
	return response;
}
try {
	const saved = await call("save", undefined, { name: "alpha", group: "prod", host: "127.0.0.1", port, username: "tester", auth: "password", secret: "secret123", defaultDir: "/home/test" });
	const nodeId = saved.data.id;
	assert.equal(readFileSync(join(dataDir, "nodes.json"), "utf8").includes("secret123"), false);
	PluginSecrets.keys.clear();
	assert.equal(new PluginSecrets(dataDir, join(dataDir, "node-workbench")).get(`node:${nodeId}:secret`), "secret123");
	const first = await call("connect", nodeId);
	assert.equal(first.event, "failure");
	const trust = events.findLast((e) => e.event === "trust_required" && e.nodeId === nodeId);
	assert.match(trust.data.fingerprint, /^SHA256:/);
	assert.equal((await call("trust", nodeId, { fingerprint: trust.data.fingerprint })).event, "result");
	const concurrent = await Promise.all([call("connect", nodeId), call("connect", nodeId)]);
	assert.equal(concurrent.filter((response) => response.event === "result").length, 1);
	assert.equal(service.connections.size, 1);
	assert.equal((await call("save", undefined, { id: nodeId, name: "alpha", group: "prod", host: "127.0.0.1", port, username: "tester", auth: "key", keyPath: "", defaultDir: "/" })).event, "failure");
	assert.equal(service.connections.size, 1);
	const opened = await call("terminal_open", nodeId, {}, "term-a");
	assert.equal(opened.event, "result");
	const conversationId = opened.data.conversationId;
	const terminalReady = async id => {
		for (let i = 0; i < 250; i++) {
			const terminal = service.connections.values().next().value.terminals.get(id);
			if (terminal && !terminal.initializing) return;
			await new Promise(resolve => setTimeout(resolve, 20));
		}
		throw new Error("terminal initialization timed out");
	};
	await terminalReady("term-a");
	assert.equal((await call("chat_state", nodeId)).event, "failure");
	assert.equal((await call("chat_prompt", nodeId, { text: "test" })).event, "failure");

	assert.equal((await call("terminal_input", nodeId, { data: "hello\r" }, "term-a", conversationId)).event, "result");
	const echoed = () => events.some((e) => e.event === "terminal_output" && e.nodeId === nodeId && e.terminalId === "term-a" && e.data.text.includes("echo:hello"));
	for (let i = 0; i < 250 && !echoed(); i++) await new Promise((r) => setTimeout(r, 20)); // poll: a fixed sleep made this timing-dependent
	assert(echoed());
	const output = await service.execute("client-a", nodeId, "term-a", "/home/test", "pwd", 5);
	assert.match(output.output, /echo:pwd/);
	assert(events.some((e) => e.event === "terminal_output" && e.nodeId === nodeId && e.terminalId === "term-a" && e.data.text.includes("echo:pwd")));
	const truncated = await service.execute("client-a", nodeId, "term-a", "/home/test", "x".repeat(70000), 5);
	assert(truncated.output.includes("[输出已截断]"));
	assert(truncated.output.length < 66000);
	const secondTerminal = await call("terminal_open", nodeId, {}, "term-b", conversationId);
	assert.equal(secondTerminal.event, "result");

	await call("terminal_open", nodeId, {}, "term-trap", conversationId);
	await terminalReady("term-trap");
	await call("terminal_input", nodeId, { data: "trap_foreground\r" }, "term-trap", conversationId);
	await assert.rejects(service.execute("client-a", nodeId, "term-trap", "/home/test", "must_not_run", 5), /手动终端正忙/);
	assert(!events.some((e) => e.event === "terminal_output" && e.terminalId === "term-trap" && e.data.text.includes("must_not_run")));
	await call("interrupt", nodeId, {}, "term-trap", conversationId);
	await assert.rejects(service.execute("client-a", nodeId, "term-trap", "/home/test", "still_not_run", 5), /手动终端正忙/);
	assert.equal((await call("read", nodeId, { path: "/home/test/a.txt" })).data.text, "hello ssh\n第二行\n");
	assert.equal((await call("write", nodeId, { path: "/home/test/new.txt", text: "node write" })).event, "result");
	assert.equal((await call("read", nodeId, { path: "/home/test/new.txt" })).data.text, "node write");
	assert.equal((await call("terminal_input", "wrong-node", { data: "oops" }, "term-a", conversationId)).event, "failure");
	service.nodes.find((n) => n.id === nodeId).fingerprint = "SHA256:changed";
	assert.equal((await call("connect", nodeId)).event, "failure");
	service.nodes.find((n) => n.id === nodeId).fingerprint = trust.data.fingerprint;
	assert.equal((await call("connect", nodeId)).event, "result");

	// Failed verification never overwrites the previous saved credential.
	assert.equal((await call("credential_test", nodeId, { secret: "wrong", persist: true })).event, "failure");
	assert.equal(service.secrets.get(`node:${nodeId}:secret`), "secret123");
	assert.equal((await call("credential_test", nodeId, { secret: "secret123", persist: false })).event, "result");
	assert.equal(service.transientSecrets.get(JSON.stringify(["client-a", nodeId])), "secret123");
	assert(!service.transientSecrets.has(JSON.stringify(["client-b", nodeId])));
	const wrong = await call("save", undefined, { name: "bad", group: "test", host: "127.0.0.1", port, username: "tester", auth: "password", secret: "wrong", defaultDir: "/" });
	const wrongId = wrong.data.id;
	assert.equal((await call("trust", wrongId, { fingerprint: trust.data.fingerprint })).event, "failure");
	assert.equal((await call("export")).data.nodes.some((n) => "secret" in n), false);
	const eventsB = [];
	const detachB = service.attach("client-b", (event) => eventsB.push(event));
	await service.handle("client-b", { type: "node_request", requestId: "b-connect", action: "connect", nodeId });
	assert.equal(eventsB.findLast((e) => e.requestId === "b-connect")?.event, "result");
	assert.equal((await call("delete", nodeId)).event, "result");
	assert(![...service.connections.values()].some((connection) => connection.nodeId === nodeId));
	detachB();

	const sourceDir = join(dataDir, "sessions"); mkdirSync(sourceDir);
	const xsh = (port = 22, name = "tester") => `[CONNECTION]\nHost=127.0.0.1\nPort=${port}\nProtocol=SSH\n[CONNECTION:AUTHENTICATION]\nUserName=${name}\nMethod=0\nPassword=encrypted-secret`;
	writeFileSync(join(sourceDir, "source.xsh"), xsh());
	const sourceResult = await call("source_add", undefined, { kind: "xshell", path: sourceDir, enabled: true });
	const sourceId = sourceResult.data.sourceId;
	let state = events.findLast((e) => e.event === "state").data;
	const imported = state.nodes.find((n) => n.sourceId === sourceId);
	assert(imported && !imported.hasSecret);
	service.secrets.set(`node:${imported.id}:secret`, "retained");
	writeFileSync(join(sourceDir, "new.xsh"), xsh(2222));
	await call("source_sync", undefined, { id: sourceId });
	assert.equal(service.secrets.get(`node:${imported.id}:secret`), "retained");
	assert.equal(service.nodes.filter((n) => n.sourceId === sourceId).length, 2);
	writeFileSync(join(sourceDir, "source.xsh"), xsh(22, "another-user"));
	await call("source_sync", undefined, { id: sourceId });
	assert(!service.secrets.has(`node:${imported.id}:secret`));
	rmSync(join(sourceDir, "source.xsh"));
	await call("source_sync", undefined, { id: sourceId });
	assert(service.nodes.find((n) => n.id === imported.id).sourceMissing);
	assert.equal((await call("connect", imported.id)).event, "failure");
	writeFileSync(join(sourceDir, "new.xsh"), "invalid");
	await call("source_sync", undefined, { id: sourceId });
	assert(service.sources.find((s) => s.id === sourceId).error);
	assert.equal(service.nodes.filter((n) => n.sourceId === sourceId).length, 2);
	assert(!readFileSync(join(dataDir, "nodes.json"), "utf8").includes("encrypted-secret"));
	assert.equal((await call("source_toggle", undefined, { id: sourceId, enabled: false })).event, "result");
	const restored = new NodeWorkbench(dataDir);
	assert.equal(restored.sources.find((s) => s.id === sourceId).enabled, false);
	restored.dispose();
	// Saved Xshell 7 passwords: real SSH auth, with a synthetic Windows identity.
	const autoDir = join(dataDir, "auto", "Xshell", "Sessions"); mkdirSync(autoDir, { recursive: true });
	const autoFile = join(autoDir, "auto.xsh");
	const autoText = `[SESSIONINFO]\nVersion=7.0\n${xsh(port)}`.replace("encrypted-secret", cryptoFixture.vectors[0].ciphertext);
	writeFileSync(autoFile, autoText);
	const autoSource = await call("source_add", undefined, { kind: "xshell", path: autoDir, enabled: false });
	const autoNode = service.nodes.find(n => n.sourceId === autoSource.data.sourceId);
	assert.equal((await call("connect", autoNode.id)).event, "failure");
	const autoTrust = events.findLast(e => e.event === "trust_required" && e.nodeId === autoNode.id);
	assert(autoTrust, "saved password should reach host verification without manual credentials");
	assert.equal((await call("trust", autoNode.id, { fingerprint: autoTrust.data.fingerprint })).event, "result");
	assert(!service.secrets.has(`node:${autoNode.id}:secret`), "source password must not be duplicated into local storage");
	const originalConnection = service.connections.get(JSON.stringify(["client-a", autoNode.id]));
	writeFileSync(autoFile, autoText.replace(cryptoFixture.vectors[0].ciphertext, cryptoFixture.vectors[1].ciphertext));
	await call("source_sync", undefined, { id: autoSource.data.sourceId });
	assert.equal(service.connections.get(JSON.stringify(["client-a", autoNode.id])), originalConnection, "source password update must not interrupt a live terminal");
	await call("disconnect", autoNode.id);
	const changedPassword = await call("connect", autoNode.id);
	assert.equal(changedPassword.data.credentialRequired, true, "next connection must use the changed source password");
	assert.equal((await call("credential_test", autoNode.id, { username: "tester", secret: "secret123" })).event, "result");
	assert.equal((await call("connect", autoNode.id)).event, "result", "explicit local credential takes precedence");

	const masterDir = join(dataDir, "master", "Xshell", "Sessions"); mkdirSync(masterDir, { recursive: true });
	mkdirSync(join(dataDir, "master", "Common"));
	writeFileSync(join(dataDir, "master", "Common", "MasterPassword.mpw"), "[MasterPassword]\nEnblMasterPasswd=1");
	writeFileSync(join(masterDir, "master.xsh"), autoText.replace(cryptoFixture.vectors[0].ciphertext, cryptoFixture.vectors[2].ciphertext));
	const masterSource = await call("source_add", undefined, { kind: "xshell", path: masterDir, enabled: false });
	const masterNode = service.nodes.find(n => n.sourceId === masterSource.data.sourceId);
	assert.equal((await call("connect", masterNode.id)).data.credentialReason, "locked");
	assert.equal((await call("xshell_unlock", masterNode.id, { masterPassword: "wrong" })).event, "failure");
	assert.equal((await call("xshell_unlock", masterNode.id, { masterPassword: "master-fixture" })).event, "result");
	await call("connect", masterNode.id);
	const masterTrust = events.findLast(e => e.event === "trust_required" && e.nodeId === masterNode.id);
	assert(masterTrust);
	assert.equal((await call("trust", masterNode.id, { fingerprint: masterTrust.data.fingerprint })).event, "result");
	const masterEventsB = []; const stopB = service.attach("master-client-b", event => masterEventsB.push(event));
	await service.handle("master-client-b", { type: "node_request", requestId: "locked-b", action: "connect", nodeId: masterNode.id });
	assert.equal(masterEventsB.findLast(e => e.requestId === "locked-b").data.credentialReason, "locked"); stopB();
	const restarted = new NodeWorkbench(dataDir, new XshellCredentials(async () => cryptoFixture.identity));
	const restartedEvents = []; restarted.attach("client-a", event => restartedEvents.push(event));
	await restarted.handle("client-a", { type: "node_request", requestId: "restart-lock", action: "connect", nodeId: masterNode.id });
	assert.equal(restartedEvents.findLast(e => e.requestId === "restart-lock").data.credentialReason, "locked"); restarted.dispose();

	const encryptedKeyPath = join(dataDir, "encrypted-key");
	writeFileSync(encryptedKeyPath, createPrivateKey(privateKey).export({ type: "pkcs1", format: "pem", cipher: "aes-256-cbc", passphrase: "key-passphrase" }));
	writeFileSync(join(masterDir, "saved-key.xsh"), autoText.replace("Method=0", `Method=1\nPrivateKey=${encryptedKeyPath}`).replace(`Password=${cryptoFixture.vectors[0].ciphertext}`, `Passphrase=${cryptoFixture.vectors[3].ciphertext}`));
	await call("source_sync", undefined, { id: masterSource.data.sourceId });
	const savedKeyNode = service.nodes.find(n => n.sourceId === masterSource.data.sourceId && n.sourceKey === "saved-key.xsh");
	const savedKeyConnect = await call("connect", savedKeyNode.id);
	const savedKeyTrust = events.findLast(e => e.event === "trust_required" && e.nodeId === savedKeyNode.id);
	assert(savedKeyTrust, `saved key passphrase must unlock the private key: ${JSON.stringify(savedKeyConnect)}`);
	assert.equal((await call("trust", savedKeyNode.id, { fingerprint: savedKeyTrust.data.fingerprint })).event, "result");
	assert(!service.secrets.has(`node:${savedKeyNode.id}:secret`));
	const browse = await call("local_key_browse", undefined, { path: dataDir });
	assert(browse.data.entries.some(entry => entry.path === encryptedKeyPath && !entry.directory));
	assert(!JSON.stringify(browse).includes("PRIVATE KEY"));
	for (const value of ["master-fixture", cryptoFixture.vectors[0].ciphertext, cryptoFixture.vectors[2].ciphertext, cryptoFixture.vectors[3].ciphertext]) {
		assert(!JSON.stringify(events).includes(value), "credentials must not appear in protocol responses");
		assert(!readFileSync(join(dataDir, "nodes.json"), "utf8").includes(value));
	}

	// Xshell key-manager names need a local private-key binding, not a password.
	const keyDir = join(dataDir, "key-sessions"); mkdirSync(keyDir);
	writeFileSync(join(keyDir, "key.xsh"), xsh(port).replace("Method=0", "Method=1\nUserKey=xshell-key-name"));
	const keySource = await call("source_add", undefined, { kind: "xshell", path: keyDir, enabled: false });
	const keyNode = service.nodes.find((n) => n.sourceId === keySource.data.sourceId);
	assert.equal(keyNode.auth, "key");
	const keyPath = join(dataDir, "id_rsa"); writeFileSync(keyPath, privateKey, { mode: 0o600 });
	assert.equal((await call("credential_test", keyNode.id, { secret: "", keyPath })).event, "failure");
	const keyTrust = events.findLast((e) => e.event === "trust_required" && e.nodeId === keyNode.id);
	assert(keyTrust);
	assert.equal((await call("credential_test", keyNode.id, { secret: "", keyPath, fingerprint: keyTrust.data.fingerprint })).event, "result");
	assert.equal(keyNode.localKeyPath, keyPath);
	assert.equal((await call("credential_test", keyNode.id, { secret: "", keyPath: join(dataDir, "missing") })).event, "failure");
	assert.equal(keyNode.localKeyPath, keyPath);
	await call("source_sync", undefined, { id: keySource.data.sourceId });
	assert.equal(keyNode.localKeyPath, keyPath);
	assert.equal((await call("connect", keyNode.id)).event, "result");
	const keyRestored = new NodeWorkbench(dataDir);
	assert.equal(keyRestored.nodes.find((n) => n.id === keyNode.id).localKeyPath, keyPath);
	keyRestored.dispose();
	keyNode.unsupported.push("proxy");
	assert.equal((await call("connect", keyNode.id)).event, "failure");
	keyNode.unsupported.pop();
	writeFileSync(join(keyDir, "key.xsh"), xsh(port, "changed").replace("Method=0", "Method=1\nUserKey=xshell-key-name"));
	await call("source_sync", undefined, { id: keySource.data.sourceId });
	assert.equal(keyNode.localKeyPath, undefined);
	// A password source can use a locally selected public-key method.
	writeFileSync(join(keyDir, "password.xsh"), xsh(port));
	await call("source_sync", undefined, { id: keySource.data.sourceId });
	const passwordNode = service.nodes.find((n) => n.sourceKey === "password.xsh");
	const override = { auth: "key", secret: "", keyPath };
	assert.equal((await call("credential_test", passwordNode.id, override)).event, "failure");
	const overrideTrust = events.findLast((e) => e.event === "trust_required" && e.nodeId === passwordNode.id);
	assert(overrideTrust, "switching to key must reach host verification without a password");
	assert.equal((await call("credential_test", passwordNode.id, { ...override, fingerprint: overrideTrust.data.fingerprint })).event, "result");
	assert.equal(passwordNode.auth, "password");
	assert.equal(passwordNode.localAuth, "key");
	assert.equal(events.findLast((e) => e.event === "state").data.nodes.find((n) => n.id === passwordNode.id).auth, "key");
	const authRestored = new NodeWorkbench(dataDir);
	assert.equal(authRestored.nodes.find((n) => n.id === passwordNode.id).localAuth, "key");
	authRestored.dispose();
	await call("source_sync", undefined, { id: keySource.data.sourceId });
	assert.equal(passwordNode.localAuth, "key");
	assert.equal((await call("connect", passwordNode.id)).event, "result");
	assert.equal((await call("credential_test", passwordNode.id, { auth: "password", secret: "wrong" })).event, "failure");
	assert.equal(passwordNode.localAuth, "key");
	assert.equal((await call("credential_test", passwordNode.id, { auth: "password", secret: "secret123" })).event, "result");
	assert.equal(passwordNode.localAuth, "password");
	writeFileSync(join(keyDir, "no-user.xsh"), xsh(port, ""));
	await call("source_sync", undefined, { id: keySource.data.sourceId });
	const noUser = service.nodes.find(n => n.sourceKey === "no-user.xsh");
	assert.equal((await call("connect", noUser.id)).data.credentialRequired, true);
	await call("credential_test", noUser.id, { username: "tester", secret: "secret123" });
	const noUserTrust = events.findLast(e => e.event === "trust_required" && e.nodeId === noUser.id);
	assert(noUserTrust);
	assert.equal((await call("credential_test", noUser.id, { username: "tester", secret: "secret123", fingerprint: noUserTrust.data.fingerprint })).event, "result");
	assert.equal(noUser.username, ""); assert.equal(noUser.localUsername, "tester");
	await call("source_sync", undefined, { id: keySource.data.sourceId });
	assert.equal((await call("connect", noUser.id)).event, "result");

	const selectedDir = join(dataDir, "selected-sessions"); mkdirSync(selectedDir);
	const selectedText = "[CONNECTION]\nHost=example.invalid\nPort=22\nProtocol=SSH\n[CONNECTION:AUTHENTICATION]\nUserName=tester\nMethod=0\n";
	writeFileSync(join(selectedDir, "one.xsh"), selectedText);
	writeFileSync(join(selectedDir, "two.xsh"), selectedText);
	writeFileSync(join(selectedDir, "blocked.xsh"), selectedText.replace("Protocol=SSH", "Protocol=TELNET"));
	const beforePreview = service.nodes.length;
	const preview = await call("source_preview", undefined, { kind: "xshell", path: selectedDir });
	assert.equal(preview.data.nodes.length, 3);
	assert.equal(service.nodes.length, beforePreview, "preview does not persist nodes");
	assert.equal((await call("source_add", undefined, { kind: "xshell", path: selectedDir, selectedKeys: ["blocked.xsh"] })).event, "result");
	assert.equal((await call("source_add", undefined, { kind: "xshell", path: selectedDir, selectedKeys: ["gone.xsh"] })).event, "result");
	const selectedSource = await call("source_add", undefined, { kind: "xshell", path: selectedDir, selectedKeys: ["one.xsh"], enabled: false });
	assert.equal(selectedSource.event, "result");
	writeFileSync(join(selectedDir, "new.xsh"), selectedText);
	await call("source_sync", undefined, { id: selectedSource.data.sourceId });
	assert.deepEqual(service.nodes.filter(n => n.sourceId === selectedSource.data.sourceId).map(n => n.sourceKey).sort(), ["blocked.xsh", "new.xsh", "one.xsh", "two.xsh"]);
	const selectionRestored = new NodeWorkbench(dataDir);
	assert.deepEqual(selectionRestored.sources.find(s => s.id === selectedSource.data.sourceId).selectedKeys, undefined);
	selectionRestored.dispose();

	console.log("✓ SSH trust, key change, authentication, terminal command/interrupt/truncation, SFTP and node isolation");
} finally {
	for (const c of [...service.connections.values()]) await call("disconnect", c.nodeId);
	service.dispose(); detach(); mock.close(); rmSync(dataDir, { recursive: true, force: true });
}
