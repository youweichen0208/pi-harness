/** Native MarketplaceManager through the production worker. No personal OMP data. */
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, existsSync, rmSync, realpathSync } from 'node:fs';
import { join, basename } from 'node:path';
import { homedir, tmpdir } from 'node:os';
import { randomUUID } from 'node:crypto';
import { pathToFileURL } from 'node:url';
import { setTimeout as sleep } from 'node:timers/promises';
import { loadOmpTestModule, ompTestRoot } from './lib/omp-runtime-location.mjs';
import { testEnv } from './lib/test-env.mjs';
import { listenIsolated } from './lib/isolated-server.mjs';
const { OmpPackages, createOmpPackageRunner } = await loadOmpTestModule('packages.js');
const root = realpathSync(mkdtempSync(join(tmpdir(), 'omp-marketplace-')));
// The SDK uses the same config directory NAME for home and project discovery.
// A unique disposable name exercises project anchoring without changing HOME
// or touching ~/.omp. Only the two directories created here are removed.
const native = realpathSync(mkdtempSync(join(homedir(), '.omp-harness-market-'))), configName = basename(native);
const project = join(root, 'project'), cwd = join(project, 'nested'), source = join(root, 'market'), plugin = join(source, 'plugin');
for (const path of [cwd, join(project, '.git'), join(project, configName), join(source, '.claude-plugin'), plugin, join(root, 'agent')]) mkdirSync(path, { recursive: true });
const counter = join(root, 'imports'); writeFileSync(counter, '');
const catalog = version => ({ name: 'fixture-market', owner: { name: 'fixture' }, plugins: [{ name: 'fixture', source: './plugin', version, description: 'Local fixture', mcpServers: { private: { command: 'unused', env: { SECRET: 'CATALOG_SECRET' } } } }] });
const manifest = version => ({ name: 'omp-market-fixture', type: 'module', version, omp: { extensions: ['./entry.js'], settings: { token: { type: 'string', default: 'MANIFEST_SECRET' } } } });
const writeSource = version => {
	writeFileSync(join(source, '.claude-plugin/marketplace.json'), JSON.stringify(catalog(version)));
	writeFileSync(join(plugin, 'package.json'), JSON.stringify(manifest(version)));
	writeFileSync(join(plugin, 'entry.js'), `import {appendFileSync} from 'node:fs'; appendFileSync(${JSON.stringify(counter)}, ${JSON.stringify(version + '\n')}); export default api => api.registerCommand('fixture-market-command', { description:'fixture', handler:async()=>{} });`);
};
writeSource('1.0.0');
const env = { ...testEnv(), PI_CONFIG_DIR: configName, PI_CODING_AGENT_DIR: join(root, 'agent'), BUN_INSTALL_CACHE_DIR: join(root, 'bun-cache'), PATH: '', Path: '' };
for (const key of Object.keys(env)) if (key.startsWith('OMP_') || key === 'ELECTRON_RUN_AS_NODE') delete env[key];
const service = new OmpPackages(root, createOmpPackageRunner(root, { env }));
const owner = { clientId: 'market-client', conversationId: 'market-conversation', cwd };
const id = 'fixture@fixture-market';
const wait = async fn => { for (let n = 0; n < 800; n++) { const result = fn(); if (result) return result; await sleep(50); } throw Error('Timed out'); };
const apply = async (plan, expected = 'success', jobOwner = owner) => {
	const job = service.start(jobOwner, randomUUID(), plan);
	await wait(() => service.get(jobOwner, job.id).phase !== 'running');
	const result = service.get(jobOwner, job.id); assert.equal(result.phase, expected, JSON.stringify(result)); return result;
};
const execute = async (operation, target, scope) => apply(await service.preview(cwd, operation, target, scope));
let requests = 0;
const remote = createServer((req, res) => { requests++; res.setHeader('Content-Type', 'application/json'); res.end(JSON.stringify({ name: 'remote-fixture', owner: { name: 'fixture' }, plugins: [] })); });
try {
	const remoteUrl = `http://127.0.0.1:${await listenIsolated(remote)}/catalog.json`;
	let view = await service.list(cwd);
	assert.equal(view.marketplace.projectRoot, join(project, configName, 'plugins'), 'SDK discovers the project anchor from a nested cwd');
	assert.deepEqual(view.marketplace.installed, []);
	const add = await service.preview(cwd, 'marketplace-add', source);
	assert(!existsSync(join(native, 'marketplaces.json')), 'preview does not register a source');
	writeSource('1.0.1'); assert.equal((await apply(add, 'failed')).error, 'conflict'); writeSource('1.0.0');
	await execute('marketplace-add', source);
	await assert.rejects(service.preview(cwd, 'marketplace-add', source), 'duplicate local catalog is rejected before any write');
	view = await service.list(cwd);
	assert.equal(view.marketplace.marketplaces[0].plugins[0].id, id);
	assert(!JSON.stringify(view).includes('CATALOG_SECRET')); assert(!JSON.stringify(view).includes('MANIFEST_SECRET'));
	assert.equal(readFileSync(counter, 'utf8'), '');
	await assert.rejects(service.preview(cwd, 'plugin-install', id));
	await assert.rejects(service.preview(cwd, 'install', 'some-package', 'project'), 'direct npm installs must not pretend project scope is supported');
	await assert.rejects(service.preview(cwd, 'marketplace-add', `${remoteUrl}?token=SECRET`));
	const remotePlan = await service.preview(cwd, 'marketplace-add', remoteUrl); assert.equal(requests, 0);
	await apply(remotePlan); assert.equal(requests, 1);
	await service.list(cwd); assert.equal(requests, 1, 'reading catalogs never refreshes the network');
	const sourceRegistry = join(native, 'marketplaces.json'), registryBefore = readFileSync(sourceRegistry, 'utf8');
	const withCredentials = JSON.parse(registryBefore); withCredentials.marketplaces.find(entry => entry.name === 'remote-fixture').sourceUri = 'https://private:SOURCE_SECRET@example.invalid/catalog.json?token=SOURCE_SECRET#SOURCE_SECRET';
	writeFileSync(sourceRegistry, JSON.stringify(withCredentials));
	assert(!JSON.stringify(await service.list(cwd)).includes('SOURCE_SECRET'));
	assert(!JSON.stringify(await service.preview(cwd, 'marketplace-refresh', 'remote-fixture')).includes('SOURCE_SECRET'));
	writeFileSync(sourceRegistry, registryBefore);
	await execute('marketplace-refresh', 'remote-fixture'); assert.equal(requests, 2);
	await execute('marketplace-remove', 'remote-fixture');
	const installUser = await service.preview(cwd, 'plugin-install', id, 'user');
	assert.equal(installUser.scope, 'user'); assert.equal(installUser.root, join(native, 'plugins'));
	assert.equal(installUser.toVersion, '1.0.0');
	const forged = { ...installUser, root: join(root, 'wrong') }; assert.equal((await apply(forged, 'failed')).error, 'conflict');
	await apply(installUser);
	await execute('plugin-install', id, 'project');
	view = await service.list(cwd);
	assert.equal(view.items.length, 0, 'Marketplace runtime links are not duplicated as npm packages');
	assert.equal(view.marketplace.installed.length, 2);
	assert(view.marketplace.installed.find(row => row.scope === 'user').shadowed);
	const sharedCache = view.marketplace.installed[0].paths[0];
	assert.equal(view.marketplace.installed[1].paths[0], sharedCache);
	assert.equal(readFileSync(counter, 'utf8'), '', 'native marketplace discovery, preview and copy do not import extensions');
	// Explicit native discovery + loading proves the installed runtime link works.
	const loader = pathToFileURL(join(ompTestRoot, 'node_modules/@oh-my-pi/pi-coding-agent/src/extensibility/extensions/loader.ts')).href;
	const probe = `const {discoverExtensionPaths,loadExtensions}=await import(${JSON.stringify(loader)}); const paths=(await discoverExtensionPaths([],process.cwd(),[],{includeAmbientHooks:false})).filter(p=>p.includes(${JSON.stringify(configName)})); const result=await loadExtensions(paths,process.cwd()); if (!paths.length || result.errors.length) throw Error('native plugin load failed'); console.log(JSON.stringify({count:paths.length})); process.exit(0);`;
	const load = async expected => {
		const before = readFileSync(counter, 'utf8');
		const loaded = await promisify(execFile)(join(ompTestRoot, 'node_modules/bun/bin/bun.exe'), ['-e', probe], { cwd, env, timeout: 30000 });
		assert.equal(JSON.parse(loaded.stdout.trim()).count, 1);
		assert.equal(readFileSync(counter, 'utf8').slice(before.length), `${expected}\n`, 'native capability loading selects the active scope');
	};
	await load('1.0.0');
	let imports = readFileSync(counter, 'utf8');
	await execute('plugin-disable', id, 'project');
	view = await service.list(cwd); assert(!view.marketplace.installed.find(row => row.scope === 'user').shadowed);
	assert.equal(view.marketplace.installed.find(row => row.scope === 'project').enabled, false);
	writeSource('1.1.0');
	view = await service.list(cwd); assert.equal(view.marketplace.marketplaces[0].plugins[0].version, '1.0.0', 'source edits do not silently refresh the cached catalog');
	await execute('marketplace-refresh', 'fixture-market');
	view = await service.list(cwd); assert(view.marketplace.installed.every(row => row.versions[0] === '1.0.0'), 'catalog refresh does not upgrade installations');
	const update = await service.preview(cwd, 'plugin-update', id, 'project');
	assert.equal(update.fromVersion, '1.0.0'); assert.equal(update.toVersion, '1.1.0');
	await apply(update);
	view = await service.list(cwd);
	assert.equal(view.marketplace.installed.find(row => row.scope === 'project').versions[0], '1.1.0');
	assert.equal(view.marketplace.installed.find(row => row.scope === 'project').enabled, false);
	assert.equal(view.marketplace.installed.find(row => row.scope === 'user').versions[0], '1.0.0');
	assert.equal(readFileSync(counter, 'utf8'), imports); await load('1.0.0');
	await execute('plugin-enable', id, 'project');
	view = await service.list(cwd); assert(view.marketplace.installed.find(row => row.scope === 'user').shadowed);
	await load('1.1.0'); imports = readFileSync(counter, 'utf8');
	const elsewhere = join(root, 'other-project'); mkdirSync(elsewhere);
	const other = await service.list(elsewhere);
	assert.deepEqual(other.marketplace.installed.map(row => row.scope), ['user']);
	await assert.rejects(service.preview(elsewhere, 'plugin-remove', id, 'project'));
	const stale = await service.preview(cwd, 'plugin-disable', id, 'project');
	const projectRegistry = join(view.marketplace.projectRoot, 'installed_plugins.json');
	const saved = JSON.parse(readFileSync(projectRegistry, 'utf8')); saved.fixtureExternalRevision = 1; writeFileSync(projectRegistry, JSON.stringify(saved));
	assert.equal((await apply(stale, 'failed')).error, 'conflict');
	await execute('marketplace-remove', 'fixture-market');
	view = await service.list(cwd); assert.equal(view.marketplace.marketplaces.length, 0); assert.equal(view.marketplace.installed.length, 2);
	await assert.rejects(service.preview(cwd, 'plugin-update', id, 'project'));
	await execute('plugin-remove', id, 'project'); assert(existsSync(sharedCache), 'user reference keeps its cache');
	await execute('plugin-remove', id, 'user'); assert(!existsSync(sharedCache), 'last reference releases cache');
	assert(existsSync(join(plugin, 'entry.js')), 'source package is never removed');
	assert.equal(readFileSync(counter, 'utf8'), imports, 'management after explicit load does not run factories');
	await execute('marketplace-add', source);
	await execute('plugin-install', id, 'project');
	const secondOwner = { ...owner, cwd: elsewhere, conversationId: 'second-project' };
	await apply(await service.preview(elsewhere, 'plugin-install', id, 'project'), 'success', secondOwner);
	const retained = (await service.list(elsewhere)).marketplace.installed[0].paths[0];
	await execute('plugin-remove', id, 'project');
	assert(existsSync(retained), 'removing one project retains the cache referenced by another project');
	await apply(await service.preview(elsewhere, 'plugin-remove', id, 'project'), 'success', secondOwner);
	assert(!existsSync(retained), 'the final project reference releases shared cache');
	const cachedCatalog = join(native, 'plugins/cache/marketplaces/fixture-market/marketplace.json'); rmSync(cachedCatalog);
	view = await service.list(cwd); assert.equal(view.marketplace.marketplaces[0].available, false, 'missing catalog does not hide the source removal action');
	await execute('marketplace-remove', 'fixture-market');
	console.log('PASS OMP Marketplace: native source lifecycle, offline preview, user/project roots, native extension discovery, scope precedence, scoped upgrade, shared cache retention, metadata conflicts and recovery from missing catalogs');
} finally {
	await service.close(); remote.closeAllConnections(); await new Promise(resolve => remote.close(resolve)); rmSync(root, { recursive: true, force: true }); rmSync(native, { recursive: true, force: true });
}
