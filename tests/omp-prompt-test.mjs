/** Real OMP prompt discovery, native refresh, file edits and ownership; optional packaged runtime. */
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, rmSync, realpathSync, symlinkSync, chmodSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { loadOmpTestModule } from './lib/omp-runtime-location.mjs';
import { testEnv } from './lib/test-env.mjs';
import { listenIsolated } from './lib/isolated-server.mjs';
const { OmpSession } = await loadOmpTestModule('session.js');
const root = realpathSync(mkdtempSync(join(tmpdir(), 'omp-prompt-'))), agent = join(root, 'omp/agent'), cwd = join(root, 'workspace');
mkdirSync(agent, { recursive: true }); mkdirSync(cwd);
writeFileSync(join(cwd, 'AGENTS.md'), 'CONTEXT_INITIAL_MARKER');
let requests = 0;
const provider = createServer((req, res) => { requests++; req.resume(); res.writeHead(200, { 'content-type': 'text/event-stream' }); res.flushHeaders(); });
const port = await listenIsolated(provider);
writeFileSync(join(agent, 'models.yml'), JSON.stringify({ providers: { fixture: { api: 'anthropic-messages', baseUrl: `http://127.0.0.1:${port}`, apiKey: 'FIXTURE_ONLY_SECRET', models: [{ id: 'fixture', contextWindow: 200000 }] } } }));
writeFileSync(join(agent, 'config.yml'), JSON.stringify({ skills: { enabled: false }, retry: { enabled: false }, cacheWarming: { enabled: false } }));
const sessions = [];
const open = async (id, restricted) => { const session = new OmpSession({ conversationId: id, dataDir: root, cwd, model: 'fixture/fixture', env: testEnv(), restricted, onChange() {} }); sessions.push(session); await session.open(); return session; };
const call = async (session, action = 'get', payload = {}) => (await session.command('harness_prompt', { action, ...payload })).data;
const find = (view, kind, scope) => { const file = view.files.find(file => file.kind === kind && file.scope === scope); assert(file, `${kind}:${scope}`); return file; };
const save = (session, file, content) => call(session, 'save', { fileId: file.id, version: file.version, content });
const remove = (session, file) => call(session, 'delete', { fileId: file.id, version: file.version });
try {
	const a = await open('a'), b = await open('b');
	const sessionId = a.state.sessionId, transcript = readFileSync(a.state.sessionFile, 'utf8');
	let view = await call(a);
	assert(view.blocks.join('\n').includes('CONTEXT_INITIAL_MARKER'));
	assert(view.sources.some(source => source.text.includes('CONTEXT_INITIAL_MARKER')));
	assert.equal(view.reloadRequired, false);
	assert(!JSON.stringify(view).includes('FIXTURE_ONLY_SECRET'));
	let user = find(view, 'system', 'user');
	view = await save(a, user, 'GLOBAL_SYSTEM_MARKER');
	assert(view.reloadRequired); assert(!view.blocks.join('\n').includes('GLOBAL_SYSTEM_MARKER'), 'save does not change the loaded prompt');
	assert.equal((await call(a, 'read', { fileId: user.id })).content, 'GLOBAL_SYSTEM_MARKER');
	view = await call(a, 'reload');
	assert(!view.reloadError); assert(!view.reloadRequired); assert(view.blocks.join('\n').includes('GLOBAL_SYSTEM_MARKER'));
	assert.equal(a.state.sessionId, sessionId); assert.equal(readFileSync(a.state.sessionFile, 'utf8'), transcript, 'prompt refresh must not rewrite history');
	assert(!(await call(b)).blocks.join('\n').includes('GLOBAL_SYSTEM_MARKER'), 'other conversations keep their own loaded prompt');
	await call(b, 'reload'); assert((await call(b)).blocks.join('\n').includes('GLOBAL_SYSTEM_MARKER'));
	await assert.rejects(save(a, user, 'STALE'), /changed/);
	user = find(view, 'system', 'user');
	const writes = await Promise.allSettled([save(a, user, 'CONCURRENT_A'), save(b, user, 'CONCURRENT_B')]);
	assert.equal(writes.filter(result => result.status === 'fulfilled').length, 1);
	view = await call(a); user = find(view, 'system', 'user');
	await save(a, user, 'GLOBAL_SYSTEM_MARKER');
	let project = find(view, 'system', 'project');
	view = await save(a, project, 'PROJECT_SYSTEM_MARKER');
	view = await call(a, 'reload');
	assert(view.blocks.join('\n').includes('PROJECT_SYSTEM_MARKER')); assert(!view.blocks.join('\n').includes('GLOBAL_SYSTEM_MARKER'));
	assert(find(view, 'system', 'project').selectedOnDisk);
	await remove(a, find(view, 'system', 'project')); view = await call(a, 'reload');
	assert(view.blocks.join('\n').includes('GLOBAL_SYSTEM_MARKER'), 'deleting the project override restores the native user fallback');
	view = await save(a, find(view, 'template', 'project'), 'TEMPLATE_NATIVE_MARKER\n{{#each contextFiles}}{{this.content}}{{/each}}');
	view = await call(a, 'reload');
	assert(view.blocks.join('\n').includes('TEMPLATE_NATIVE_MARKER')); assert(view.blocks.join('\n').includes('CONTEXT_INITIAL_MARKER'));
	await remove(a, find(view, 'template', 'project')); view = await call(a, 'reload');
	const context = view.files.find(file => file.path === join(cwd, 'AGENTS.md')); assert(context);
	await assert.rejects(remove(a, context), /cannot be deleted/);
	await save(a, context, 'CONTEXT_CHANGED_MARKER'); view = await call(a, 'reload');
	assert(view.sources.some(source => source.text.includes('CONTEXT_CHANGED_MARKER')));
	assert(!view.blocks.join('\n').includes('CONTEXT_INITIAL_MARKER'));
	user = find(view, 'system', 'user');
	for (const content of [42, 'x'.repeat(512 * 1024 + 1), '\ud800']) await assert.rejects(save(a, user, content), /UTF-8|512/);
	await assert.rejects(call(a, 'read', { fileId: join(agent, 'models.yml') }), /unavailable/);
	const disk = readFileSync(user.path, 'utf8');
	writeFileSync(user.path, Buffer.from([0xff, 0xfe]));
	assert.equal(find(await call(a), 'system', 'user').editable, false);
	await assert.rejects(save(a, user, 'REJECT'), /read-only/);
	writeFileSync(user.path, disk);
	if (process.platform !== 'win32') {
		chmodSync(user.path, 0o640); user = find(await call(a), 'system', 'user');
		await save(a, user, 'MODE_PRESERVED'); assert.equal(statSync(user.path).mode & 0o777, 0o640);
		const target = join(root, 'outside.txt'); writeFileSync(target, 'OUTSIDE_UNTOUCHED'); rmSync(user.path); symlinkSync(target, user.path);
		assert.equal(find(await call(a), 'system', 'user').editable, false);
		await assert.rejects(save(a, user, 'REJECT'), /read-only/); assert.equal(readFileSync(target, 'utf8'), 'OUTSIDE_UNTOUCHED');
		rmSync(user.path); writeFileSync(user.path, 'GLOBAL_SYSTEM_MARKER');
	}
	assert.equal(requests, 0, 'file editing and native refresh must not call the model');
	await a.stop(); assert.equal(await a.requestIfOpen('harness_prompt', { action: 'get' }), undefined);
	await a.open(); view = await call(a); assert(view.blocks.join('\n').includes('CONTEXT_CHANGED_MARKER'));
	assert.equal(a.state.sessionId, sessionId);
	await a.prompt('Hold stream for prompt file isolation');
	for (let i = 0; requests === 0 && i < 200; i++) await new Promise(resolve => setTimeout(resolve, 25));
	assert.equal(requests, 1);
	user = find(await call(a), 'system', 'user');
	await assert.rejects(save(a, user, 'BUSY_REJECT'), /Stop/); await assert.rejects(call(a, 'reload'), /Stop/);
	assert.equal(readFileSync(user.path, 'utf8'), 'GLOBAL_SYSTEM_MARKER'); await a.stop();
	await a.open();
	const interruptedHistory = readFileSync(a.state.sessionFile, 'utf8');
	assert(interruptedHistory.includes('Hold stream for prompt file isolation'));
	await call(a, 'reload');
	assert.equal(readFileSync(a.state.sessionFile, 'utf8'), interruptedHistory, 'refresh preserves existing interrupted history too');
	const restricted = await open('restricted', { systemPrompt: 'Restricted', toolNames: [] });
	await assert.rejects(call(restricted), /unavailable/);
	console.log('PASS OMP prompt files: native source discovery, literal/template/context refresh, precedence, history preservation, conflict/validation, permission and symlink protection, Stop/reopen and restricted/busy isolation');
} finally { await Promise.allSettled(sessions.map(session => session.close())); provider.closeAllConnections(); await new Promise(resolve => provider.close(resolve)); rmSync(root, { recursive: true, force: true }); }
