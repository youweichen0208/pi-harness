import { mergeSnapshot, snapshotStates } from "./lib/snapshots.mjs";
/** Native local command output reaches UI state without becoming model history. */
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, rmSync, realpathSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { stripVTControlCharacters } from 'node:util';
import { OmpChatService } from '../dist/server/omp/chat-service.js';
import { listenIsolated, startIsolatedHarness } from './lib/isolated-server.mjs';
import { scrubHostEnv } from './lib/test-env.mjs';
scrubHostEnv();
for (const key of Object.keys(process.env)) if (/API_KEY|TOKEN|SECRET|PASSWORD|^ANTHROPIC_|^OPENAI_/.test(key)) delete process.env[key];
const root = realpathSync(mkdtempSync(join(tmpdir(), 'omp-command-output-'))), data = join(root, 'data'), agent = join(data, 'omp/agent');
mkdirSync(agent, { recursive: true });
const requests = [], events = [], native = [];
let service, harness, browser, holdNext = false, release;
const wait = async (predicate, label) => { for (let i = 0; i < 800; i++) { if (await predicate()) return; await new Promise(resolve => setTimeout(resolve, 25)); } throw Error('Timed out ' + label); };
const provider = createServer(async (req, res) => {
	let raw = ''; for await (const chunk of req) raw += chunk; requests.push(JSON.parse(raw));
	res.writeHead(200, { 'content-type': 'text/event-stream' });
	const emit = (type, data) => res.write(`event: ${type}\ndata: ${JSON.stringify({ type, ...data })}\n\n`);
	emit('message_start', { message: { id: 'fixture', type: 'message', role: 'assistant', model: 'fixture', content: [], usage: { input_tokens: 10, output_tokens: 0 } } });
	if (holdNext) { holdNext = false; await new Promise(resolve => { release = resolve; res.once('close', resolve); }); }
	if (res.destroyed) return;
	emit('content_block_start', { index: 0, content_block: { type: 'text', text: '' } });
	emit('content_block_delta', { index: 0, delta: { type: 'text_delta', text: 'Native output fixture reply.' } });
	emit('content_block_stop', { index: 0 });
	emit('message_delta', { delta: { stop_reason: 'end_turn' }, usage: { output_tokens: 6 } });
	emit('message_stop', {}); res.end();
});
try {
	const port = await listenIsolated(provider);
	writeFileSync(join(agent, 'models.yml'), JSON.stringify({ providers: { fixture: { api: 'anthropic-messages', baseUrl: `http://127.0.0.1:${port}`, apiKey: 'fixture', models: [{ id: 'fixture', contextWindow: 1000000 }] } } }));
	writeFileSync(join(agent, 'config.yml'), JSON.stringify({ skills: { enabled: false }, compaction: { enabled: false }, retry: { enabled: false }, cacheWarming: { enabled: false } }));
	service = new OmpChatService(root, join(data, 'client-state.json'));
	const client = await service.attach('output', event => events.push(event));
	await client.setModel('fixture/fixture');
	const first = client.session, firstId = client.conversationId;
	first.subscribe(frame => { if (frame.type === 'command_output') native.push(frame.text); });
	const original = readFileSync(first.state.sessionFile);
	await client.prompt('/context', undefined, undefined, 'context');
	await wait(() => native.length > 0, 'native command output');
	const report = stripVTControlCharacters(native[0]);
	assert(first.state.commandOutputs?.some(output => output.text === report), 'native output must be visible as plain text in product state');
	client.flushSnapshot();
	assert(snapshotStates(events).at(-1).commandOutputs.some(output => output.text === report));
	assert.equal(client.queryPromptReceipt('context').commandExecuted, true, 'local command must not leave a phantom model reply');
	assert.equal(client.queryPromptReceipt('context').attachmentsConsumed, false);
	assert.equal(requests.length, 0);
	assert.equal(first.state.messages.length, 0);
	assert(readFileSync(first.state.sessionFile).equals(original), 'displaying a command cannot append synthetic model messages');
	await client.newChat(true);
	const secondId = client.conversationId;
	assert.equal(client.session.state.commandOutputs?.length ?? 0, 0);
	const marker = events.length;
	await first.command('prompt', { message: '/context' });
	assert.equal(first.state.commandOutputs.length, 2);
	assert(!events.slice(marker).some(event => (event.type === 'snapshot' || event.type === 'snapshot_delta') && event.state.conversationId === secondId && event.state.commandOutputs?.length), 'background output stays in its owning conversation');
	await client.switchConversation(firstId);
	assert.equal(first.state.commandOutputs.length, 2);
	await client.abort();
	const stoppedGeneration = first.generation;
	const replay = []; const sink = event => replay.push(event);
	client.attachSink(sink, false); client.detachSink(sink);
	assert.equal(replay.find(event => event.type === 'snapshot').state.commandOutputs.length, 2, 'reconnect preserves recent local output');
	assert.equal(first.generation, stoppedGeneration);
	await client.prompt('Continue normally');
	await wait(() => !first.state.running, 'normal reply');
	assert.equal(requests.length, 1);
	const modelText = requests[0].messages.map(message => typeof message.content === 'string' ? message.content : message.content.filter(block => block.type === 'text').map(block => block.text).join('\n')).join('\n');
	assert(!modelText.includes(report), 'command report never enters a subsequent model request');
	holdNext = true;
	await client.prompt('Held task'); await wait(() => requests.length === 2 && release, 'held provider response');
	await client.prompt('/context', undefined, 'steer', 'context-while-running');
	assert.equal(client.queryPromptReceipt('context-while-running').commandExecuted, true);
	assert(first.state.running, 'a local command during generation must not mark that task complete');
	assert.equal(first.state.queue?.steering.length ?? 0, 0, 'local command must not become a queued model prompt');
	assert.equal(requests.length, 2);
	release(); await wait(() => !first.state.running, 'held task settles');
	await client.prompt('/new', undefined, undefined, 'new');
	assert.equal(first.state.commandOutputs.length, 0, 'a new native history clears prior temporary output');
	assert.equal(requests.length, 2);
	if (process.argv.includes('--browser')) {
		await service.disposeAll(); service = undefined;
		const { chromium } = await import('playwright-core');
		const { CHROME_PATH } = await import('./lib/chrome.mjs');
		harness = await startIsolatedHarness({ env: { PI_WEB_DATA_DIR: data, PI_WEB_CWD: root } });
		browser = await chromium.launch({ executablePath: CHROME_PATH || chromium.executablePath() });
		const page = await browser.newPage();
		let state, ready = false;
		await page.routeWebSocket('**/ws', route => {
			const upstream = route.connectToServer();
			upstream.onMessage(wire => { const event = JSON.parse(String(wire)); state = mergeSnapshot(state, event); if (event.type === 'ready') ready = true; route.send(wire); });
		});
		await page.goto(`http://127.0.0.1:${harness.port}`);
		await wait(() => ready && state?.model, 'browser ready');
		const input = page.locator('.inputbar textarea');
		await input.fill('/context'); await page.locator('.composer-action.send').click();
		const output = page.locator('.omp-command-output').last(); await output.waitFor();
		await wait(() => state?.commandOutputs?.length && !state.isStreaming, 'command snapshot');
		assert.equal(await output.locator('pre').textContent(), state.commandOutputs.at(-1).text);
		await wait(async () => (await input.inputValue()) === '', 'cleared local command draft');
		assert.equal(await page.locator('.pending-echo').count(), 0, 'local command must not show pending model reply');
		assert.equal(requests.length, 2);
		const summary = output.locator('summary');
		await summary.focus(); await page.keyboard.press('Enter');
		assert.equal(await output.evaluate(element => element.open), false);
		await page.keyboard.press('Enter');
		assert.equal(await output.evaluate(element => element.open), true);
		await output.locator('.copy-btn').click();
		await page.getByRole('button', { name: '已复制', exact: true }).waitFor();
		const literal = '<script>window.commandOutputExecuted=1</script>';
		await input.fill('/model ' + literal); await page.locator('.composer-action.send').click();
		await wait(() => state.commandOutputs.length === 2 && !state.isStreaming, 'literal model error output');
		assert((await output.locator('pre').textContent()).includes(literal));
		assert.equal(await output.locator('script').count(), 0);
		assert.equal(await page.evaluate(() => window.commandOutputExecuted), undefined, 'native command text is never interpreted as HTML');
		await page.screenshot({ path: join(tmpdir(), 'omp-command-output.png') });
		const beforeReload = state.commandOutputs.at(-1).id;
		ready = false; await page.reload(); await wait(() => ready, 'browser reconnect');
		assert.equal(state.commandOutputs.at(-1).id, beforeReload);
		await page.setViewportSize({ width: 390, height: 844 });
		await output.waitFor();
		assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'command output must not widen a narrow window');
		await page.screenshot({ path: join(tmpdir(), 'omp-command-output-mobile.png') });
		assert.equal(requests.length, 2, 'local command display, copy and reload never call a model');
		writeFileSync(join(root, 'note.md'), '# Command output fixture\n\nWiki content stays unchanged.\n');
		await page.setViewportSize({ width: 1280, height: 900 }); ready = false;
		await page.goto(`http://127.0.0.1:${harness.port}/?${new URLSearchParams({ 'wiki-window': '1', cwd: root, doc: 'note.md', client: 'command-wiki', model: 'fixture/fixture' })}`);
		await page.locator('.wiki-prose .fp-rich-document').waitFor();
		await page.locator('.wiki-ask-toggle').click();
		await wait(() => ready && state?.wiki && state?.model, 'Wiki assistant ready');
		const wiki = page.locator('.wiki-assistant');
		assert.equal(await wiki.locator('.omp-command-output').count(), 0, 'ordinary chat output cannot leak into a Wiki conversation');
		await wiki.locator('textarea').fill('/context'); await wiki.locator('.composer-action.send').click();
		await wiki.locator('.omp-command-output pre').waitFor();
		await wait(() => !state.isStreaming && state.commandOutputs?.length === 1, 'Wiki command finishes locally');
		assert.equal(state.messages.length, 0, 'local output alone must exit the Wiki welcome state');
		const wikiOutput = wiki.locator('.omp-command-output');
		assert.equal(await wikiOutput.locator('pre').textContent(), state.commandOutputs[0].text);
		await wikiOutput.locator('.copy-btn').click();
		await wiki.getByRole('button', { name: '已复制', exact: true }).waitFor();
		await page.locator('.wiki-ask-toggle').click();
		await wiki.waitFor({ state: 'hidden' });
		await page.locator('.wiki-ask-toggle').click();
		await wikiOutput.locator('pre').waitFor();
		await wiki.locator('.wiki-assistant-header button[aria-pressed]').click();
		await page.locator('.wiki-assistant.is-docked .omp-command-output pre').waitFor();
		await page.screenshot({ path: join(tmpdir(), 'omp-command-output-wiki.png') });
		assert.equal(await wiki.locator('.pending-echo').count(), 0);
		assert.equal(requests.length, 2, 'Wiki scope attachments do not turn a local command into a model request');
		assert.equal(readFileSync(join(root, 'note.md'), 'utf8'), '# Command output fixture\n\nWiki content stays unchanged.\n');
		console.log('PASS command output browser: plain text, no pending echo, keyboard folding, copy, reconnect and narrow viewport');
		console.log('PASS Wiki command output: shared display, separate conversation and zero model calls');
	}
	console.log('PASS native command output: exact display, local receipt, no model/history injection, background isolation, reconnect, Stop and new-session reset');
} finally { release?.(); await browser?.close(); await harness?.stop(); await service?.disposeAll(); provider.closeAllConnections(); await new Promise(resolve => provider.close(resolve)); rmSync(root, { recursive: true, force: true }); }
