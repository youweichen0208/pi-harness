import { mkdtemp, rm, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createHash, randomUUID } from "node:crypto";
import { afterEach, beforeEach, expect, test, vi } from "vitest";
import { TaskRecord, taskDetail, taskSummaries } from "../../server/subagents/tasks.js";
import type { UiSubagentProgress } from "../../server/protocol.js";
let root: string;
const task: UiSubagentProgress = { sourceId: "repo", source: "Repo", root: "/repo", task: "Investigate", phase: "queued" };
const result = { ...task, status: "completed" as const, text: "Answer", evidenceStatus: "unverified" as const, truncated: false, durationMs: 4 };
beforeEach(async () => { root = await mkdtemp(join(tmpdir(), "subagent-record-")); vi.stubEnv("PI_WEB_DATA_DIR", root); });
afterEach(async () => { vi.unstubAllEnvs(); await rm(root, { recursive: true, force: true }); });
test("persists bounded paginated records, scopes access and supports historical reload", async () => {
	const session = randomUUID();
	const record = new TaskRecord(session, "call", "turn", task, () => {});
	for (let i = 0; i < 70; i++) record.event({ type: "tool_end", text: "x".repeat(30000), toolCallId: String(i) });
	await record.finish(result);
	const first = await taskDetail(session, record.id, new Set(["call"]));
	expect(first.events).toHaveLength(50); expect(first.nextCursor).toBe(50); expect(first.events[0].truncated).toBe(true);
	expect(first.truncated).toBe(true);
	const second = await taskDetail(session, record.id, new Set(["call"]), 50);
	expect(second.events[0].seq).toBe(50); expect(second.resultText).toContain("Answer");
	await expect(taskDetail(session, record.id, new Set(["other"]))).rejects.toThrow(/branch/);
	await expect(taskDetail("other", record.id, new Set(["call"]))).rejects.toThrow();
	await expect(taskDetail(session, "../../file", new Set())).rejects.toThrow(/Invalid/);
});
test("truncates events instead of losing the terminal result when the journal exceeds 2 MiB", async () => {
	const session = randomUUID();
	const record = new TaskRecord(session, "call", "turn", task, () => {});
	for (let i = 0; i < 70; i++) record.event({ type: "tool_end", text: "x".repeat(30000), toolCallId: String(i) });
	await record.finish({ ...result, text: "x".repeat(700 * 1024) });
	const saved = await taskDetail(session, record.id, new Set(["call"]));
	expect(saved.task.phase).toBe("completed");
	expect(saved.resultText?.length).toBeGreaterThan(700 * 1024);
	expect(saved.truncated).toBe(true);
	expect(saved.events.length).toBeLessThan(60);
	expect(Buffer.byteLength(JSON.stringify(saved))).toBeLessThanOrEqual(2 * 1024 * 1024);
});
test("keeps event sequence cursors monotonic after journal trimming", async () => {
	const session = randomUUID();
	const record = new TaskRecord(session, "call", "turn", task, () => {});
	for (let i = 0; i < 70; i++) record.event({ type: "tool_end", text: "x".repeat(30000), toolCallId: String(i) });
	record.data.resultText = "x".repeat(700 * 1024);
	record.update({});
	record.data.resultText = undefined;
	record.update({});
	record.event({ type: "answer", text: "late answer" });
	await record.finish(result);
	const saved = await taskDetail(session, record.id, new Set(["call"]), 70);
	expect(saved.events.map(event => event.text)).toEqual(["late answer"]);
	expect(saved.events[0].seq).toBe(70);
});
test("stop is scoped to one task, remains stopping while SDK drains, and is idempotent", async () => {
	const session = randomUUID();
	const first = new TaskRecord(session, "call", "turn", task, () => {});
	const second = new TaskRecord(session, "call", "turn", task, () => {});
	first.update({ phase: "running" });
	await taskDetail(session, first.id, new Set(["call"]), 0, true);
	first.update({ phase: "running" });
	expect(first.data.task.phase).toBe("stopping"); expect(second.controller.signal.aborted).toBe(false);
	await first.finish({ ...result, status: "cancelled" }); await second.finish(result);
	expect((await taskDetail(session, first.id, new Set(["call"]), 0, true)).task.phase).toBe("cancelled");
});
test("restart recovers orphaned task summaries without continuing a model", async () => {
	const session = randomUUID(); const record = new TaskRecord(session, "call", "turn", task, () => {});
	await record.finish(result);
	const path = join(root, "subagent-tasks", createHash("sha256").update(session).digest("hex"), `${record.id}.json`);
	const data = JSON.parse(await readFile(path, "utf8")); data.task.phase = "running"; delete data.resultText;
	await writeFile(path, JSON.stringify(data));
	await writeFile(`${path}.summary.json`, JSON.stringify({ toolCallId: "call", task: data.task }));
	vi.resetModules();
	const restarted = await import("../../server/subagents/tasks.js");
	await restarted.recoverTaskSummaries(session);
	expect(restarted.taskSummaries(session, new Set(["call"]))[0].tasks[0].phase).toBe("failed");
	expect(restarted.taskSummaries(session, new Set(["other"]))).toEqual([]);
	const restored = await restarted.taskDetail(session, record.id, new Set(["call"]));
	expect(restored.task.phase).toBe("failed"); expect(restored.resultText).toContain("service restart");
});

test("finished children remain ordered beside active siblings until the parent result arrives", async () => {
	const session = randomUUID();
	const first = new TaskRecord(session, "call", "turn", { ...task, taskIndex: 0, task: "x".repeat(1000) }, () => {});
	const second = new TaskRecord(session, "call", "turn", { ...task, taskIndex: 1 }, () => {});
	await second.finish({ ...result, status: "cancelled" });
	const summaries = taskSummaries(session, new Set(["call"]))[0].tasks;
	expect(summaries.map(task => task.taskId)).toEqual([first.id, second.id]);
	expect(summaries[0].task).toHaveLength(500);
	expect(summaries[1].phase).toBe("cancelled");
	await first.finish(result);
	expect(taskSummaries(session, new Set(["call"]), new Set(["call"]))).toEqual([]);
});
