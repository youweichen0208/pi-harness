import assert from 'node:assert/strict';
import { createServer } from 'vite';
import { mkdirSync } from 'node:fs';
import { chromium } from 'playwright-core';
import { CHROME_PATH } from './lib/chrome.mjs';
import { playgroundFixture } from './lib/playground-fixture.mjs';
const fixture = await playgroundFixture();
const dev = await createServer({ configFile: 'web/vite.config.ts', server: { port: 0, host: '127.0.0.1', proxy: { '/api': { target: fixture.base, changeOrigin: true }, '/ws': { target: fixture.base, changeOrigin: true, ws: true, configure(proxy) { proxy.on('proxyReqWs', req => req.setHeader('origin', fixture.base)); } } } } });
await dev.listen();
const address = dev.httpServer?.address();
assert(address && typeof address === 'object');
let browser;
try {
	browser = await chromium.launch({ executablePath: CHROME_PATH });
	const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
	const errors = [];
	page.on('pageerror', error => errors.push(error.message));
	const stamp = Date.now();
	const findings = Array.from({ length: 5 }, (_, i) => ({ kind: i === 4 ? 'inference' : 'implementation', statement: `发现 ${i + 1}：快照由统一入口生成，按流式活动状态选择节流间隔。`, citations: [{ path: 'agent-service.ts', startLine: 1, endLine: 2, excerpt: 'const interval = 60;\nexport { interval };' }] }));
	const results = Array.from({ length: 3 }, (_, i) => ({ sourceId: `repo:${i}`, source: `项目 ${i + 1}`, root: fixture.root, title: `调研任务 ${i + 1}`, task: ['找出快照推送实现与节流间隔，只回答两点。', '核对数据流与缓存结构。', '检查发布脚本是否影响归档。'][i], status: 'completed', text: '调查完成', evidenceStatus: 'checked', durationMs: (i + 1) * 1000, report: { summary: '全量与增量快照由同一入口产生；节流随流式活动状态变化。', findings, connections: [], openQuestions: [], checkedAt: new Date().toISOString() } }));
	const args = JSON.stringify({ action: 'run', tasks: results.map(({ sourceId, task, title }) => ({ sourceId, task, title })) });
	const messages = [{ id: 'u', role: 'user', content: [{ type: 'text', text: '调查快照与缓存' }], timestamp: stamp }, { id: 'a', role: 'assistant', model: 'test-model', timestamp: stamp + 1, content: [{ type: 'toolCall', id: 'sub', name: 'subagent', argumentsText: args }] }, { id: 'result', role: 'toolResult', toolCallId: 'sub', toolName: 'subagent', durationMs: 3200, timestamp: stamp + 2, content: [{ type: 'text', text: JSON.stringify({ workspace: { id: 'fixture', name: '工作区' }, results }) }] }];
	let base;
	await page.routeWebSocket(/\/ws(?:\?|$)/, route => {
		const upstream = route.connectToServer();
		route.onMessage(w => upstream.send(w));
		upstream.onMessage(w => {
			const message = JSON.parse(String(w));
			if (message.type === 'snapshot' || message.type === 'snapshot_delta') {
				base = { ...base, ...message.state };
				route.send(JSON.stringify({ type: 'snapshot', state: { ...base, piConfigured: true, isStreaming: false, messages, streamingMessage: null, taskProgress: null } }));
			} else route.send(w);
		});
	});
	await page.goto(`http://127.0.0.1:${address.port}/?token=${fixture.token}`);
	await page.locator('.subagent-task-group-head').click();
	assert.equal(await page.locator('.subagent-task-row').count(), 3);
	const first = page.locator('.subagent-task-row').first();
	await first.click();
	await page.locator('.subagent-task-result').waitFor();
	assert.match(await page.locator('.subagent-task-result').innerText(), /全量与增量快照/);
	assert.equal(await page.locator('.subagent-task-result li').count(), 5);
	assert.match(await page.locator('.subagent-task-result li').last().innerText(), /推断/);
	await page.locator('.subagent-task-result li details summary').first().click();
	assert.match(await page.locator('.subagent-task-result li details pre').first().textContent(), /interval = 60/);
	await page.locator('.subagent-task-instruction summary').click();
	assert.match(await page.locator('.subagent-task-instruction').innerText(), /只回答两点/);
	await page.getByRole('button', { name: '执行过程', exact: true }).click();
	assert.match(await page.locator('.subagent-drawer-content').innerText(), /此记录未保存执行步骤/);
	assert.equal(await page.locator('.subagent-task-timeline li').count(), 0);
	await page.getByRole('button', { name: '结果', exact: true }).click();
	mkdirSync('tests/scratch/oil-subagent', { recursive: true });
	await page.screenshot({ path: 'tests/scratch/oil-subagent/desktop.png' });
	await page.evaluate(() => document.documentElement.setAttribute('data-appearance', 'dark'));
	await page.screenshot({ path: 'tests/scratch/oil-subagent/dark.png' });
	await page.setViewportSize({ width: 390, height: 844 });
	assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
	await page.screenshot({ path: 'tests/scratch/oil-subagent/mobile-report.png' });
	await page.getByRole('button', { name: '执行过程', exact: true }).click();
	await page.screenshot({ path: 'tests/scratch/oil-subagent/mobile.png' });
	await page.setViewportSize({ width: 720, height: 1000 });
	await page.getByRole('button', { name: '结果', exact: true }).click();
	await page.screenshot({ path: 'tests/scratch/oil-subagent/200-percent-equivalent.png' });
	assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
	await page.keyboard.press('Escape');
	assert(await first.evaluate(element => element === document.activeElement), 'closing restores the trigger row focus');
	assert.deepEqual(errors, []);
	console.log('PASS current subagent drawer report, citations, legacy steps, dynamic port, dark/mobile and focus');
} finally { await browser?.close(); await dev.close(); await fixture.stop(); }
