/** Main-chat document dialogs and configured knowledge-library windows, zero external tokens. */
import { createServer } from "node:http";
import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { once } from "node:events";
import { mkdtempSync, mkdirSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { chromium } from "playwright-core";
import { CHROME_PATH } from "./lib/chrome.mjs";
import { portUp } from "./lib/port-utils.mjs";
import { testEnv } from "./lib/test-env.mjs";

const port = 9396;
assert.equal(await portUp(port), false, "isolated port must be free");
assert.equal(await portUp(port + 1), false);
const base = realpathSync(mkdtempSync(join(tmpdir(), "doc-evidence-")));
const cwd = join(base, "workspace"), agent = join(base, "agent");
mkdirSync(agent); mkdirSync(join(cwd, "knowledge/evidence/source"), { recursive: true });
writeFileSync(join(cwd, "README.md"), "# Knowledge entry\n\nSelected exact passage.\n\n[Other](./other.md)\n\n" + Array.from({length: 80}, (_, i) => `Paragraph ${i}.\n\n`).join(""));
writeFileSync(join(cwd, "knowledge/manifest.json"), JSON.stringify({ kind: "pi-harness-knowledge", version: 1, evidenceDirectory: "evidence" }));
const rawPath = join(cwd, "knowledge/evidence/source/original.md"), raw = "# Archived evidence\n\n原始文件内容应保持不变。\n";
writeFileSync(rawPath, raw);
writeFileSync(join(cwd, "background.ts"), "export const background = true;\n");
writeFileSync(join(cwd, "other.md"), "# Other document\n\nOther text.\n");
let releaseReply;
let responseGate = new Promise(resolve => { releaseReply = resolve; });
const mock = createServer(async (req, res) => {
	for await (const chunk of req) {}
	res.writeHead(200, { "content-type": "text/event-stream" });
	await responseGate;
	for (const [delta, finish_reason] of [[{role: "assistant", content: Array.from({length: 50}, (_, i) => `Reply paragraph ${i}.\n\n`).join("")}, null], [{}, "stop"]]) res.write(`data: ${JSON.stringify({id: "local", object: "chat.completion.chunk", choices: [{index: 0, delta, finish_reason}]})}\n\n`);
	res.end("data: [DONE]\n\n");
});
await new Promise(r => mock.listen(port + 1, "127.0.0.1", r));
writeFileSync(join(agent, "models.json"), JSON.stringify({ providers: { fixture: { api: "openai-completions", baseUrl: `http://127.0.0.1:${port + 1}`, apiKey: "unused", models: [{ id: "unused", name: "Unused local model", input: ["text"], contextWindow: 32000, maxTokens: 4096 }] } } }));
writeFileSync(join(agent, "settings.json"), JSON.stringify({ defaultProvider: "fixture", defaultModel: "unused" }));
writeFileSync(join(agent, "auth.json"), JSON.stringify({ fixture: { type: "api_key", key: "unused" } }));
const server = spawn(process.execPath, ["dist/server/index.js"], { env: { ...testEnv(), PORT: String(port), PI_WEB_TOKEN: "", PI_WEB_HOST: "127.0.0.1", PI_WEB_CWD: cwd, PI_WEB_DATA_DIR: join(base, "data"), PI_CODING_AGENT_DIR: agent }, stdio: ["ignore", "pipe", "pipe"] });

let log = "", browser;
server.stdout.on("data", data => { log += data; }); server.stderr.on("data", data => { log += data; });
try {
	for (let i = 0; i < 150 && !await portUp(port); i++) { assert.equal(server.exitCode, null, log); await new Promise(r => setTimeout(r, 100)); }
	browser = await chromium.launch({ executablePath: CHROME_PATH || chromium.executablePath() });
	const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
	page.setDefaultTimeout(20000);
	const errors = [], sent = [];
	page.on("pageerror", e => errors.push(e.message));
	page.on("websocket", ws => ws.on("framesent", ({ payload }) => sent.push(JSON.parse(String(payload)))));
	await page.goto(`http://127.0.0.1:${port}`);
	await page.locator(".conn-dot.ok").first().waitFor({ state: "attached" });
	await page.locator(".inputbar textarea").fill("keep my draft");
	await page.locator(".file-name", { hasText: "README.md" }).first().click();
	const dialog = page.locator(".wiki-document-dialog");
	await dialog.waitFor();
	const editor = dialog.locator(".fp-rich-document"); await editor.waitFor();
	assert.equal(await dialog.locator(".inputbar textarea").inputValue(), "keep my draft");
	assert.equal(page.context().pages().length, 1);
	assert.equal(await dialog.locator(".inputbar").count(), 1);
	await editor.evaluate(el => { el.focus(); const range = document.createRange(); range.selectNodeContents(el); range.collapse(false); const selection = getSelection(); selection.removeAllRanges(); selection.addRange(range); });
	await page.keyboard.type(" Auto saved text.");
	await page.waitForFunction(() => document.querySelector(".fp-save-state.saved"), { }, { timeout: 1500 }).catch(() => {});
	for (let i=0;i<80 && !readFileSync(join(cwd,"README.md"),"utf8").includes("Auto saved text.");i++) await new Promise(r=>setTimeout(r,100));
	assert(readFileSync(join(cwd,"README.md"),"utf8").includes("Auto saved text."), "idle edits save to disk");
	await dialog.locator(".inputbar textarea").fill("update the current document");
	await dialog.locator(".inputbar textarea").press("Enter");
	for(let i=0;i<80&&!sent.some(m=>m.type==="prompt");i++) await new Promise(r=>setTimeout(r,100));
	const prompt=sent.find(m=>m.type==="prompt"); assert(prompt,"prompt sent");
	assert(prompt.attachments.some(a=>a.editorSnapshot?.text.includes("Auto saved text.")),"current editor snapshot sent");
	await dialog.locator(".wiki-modal-header").getByRole("button", { name: "关闭", exact: true }).click();
	await dialog.waitFor({ state: "detached" });
	assert.equal(await page.locator(".attach-chip.current-file").count(), 0, "closing removes the current file reference");
	assert.equal(sent.filter(m=>m.type==="abort").length,0,"closing dialog does not stop agent");
	assert.equal(sent.filter(m=>m.type==="switch_conversation").length,0,"document dialog shares conversation");
	releaseReply();
	// Ordinary code previews use the same document lifecycle but remain manually saved.
	await page.locator(".file-name", { hasText: "background.ts" }).click();
	const codeEditor = page.locator(".fp-editor"); await codeEditor.waitFor();
	await codeEditor.fill("export const local = true;\n");
	await page.waitForTimeout(900);
	assert.equal(readFileSync(join(cwd, "background.ts"), "utf8"), "export const background = true;\n");
	writeFileSync(join(cwd, "background.ts"), "external edit\n");
	await page.locator(".fp-header-save").click();
	await page.getByRole("button", { name: "覆盖磁盘文件", exact: true }).waitFor();
	assert.equal(await codeEditor.inputValue(), "export const local = true;\n");
	await page.locator(".fp-back").click();
	await page.locator(".fp-leave").getByRole("button", { name: "取消", exact: true }).click();
	assert.equal(await codeEditor.inputValue(), "export const local = true;\n");
	page.once("dialog", dialog => dialog.accept());
	await page.getByRole("button", { name: "覆盖磁盘文件", exact: true }).click();
	for (let i=0;i<60 && readFileSync(join(cwd,"background.ts"),"utf8")!=="export const local = true;\n";i++) await new Promise(r=>setTimeout(r,100));
	assert.equal(readFileSync(join(cwd,"background.ts"),"utf8"), "export const local = true;\n");
	await page.locator(".fp-back").click();
	await codeEditor.waitFor({ state: "detached" });
	const popup=page.waitForEvent("popup");
	await page.getByRole("button",{name:"知识库",exact:true}).click();
	const wiki=await popup; wiki.setDefaultTimeout(20000); wiki.on("pageerror",e=>errors.push(e.message));
	await wiki.getByRole("dialog",{name:"选择知识库文件夹"}).waitFor();
	const api=async(action, extra={})=>wiki.evaluate(async({action,extra})=>{const r=await fetch("/api/knowledge-library",{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify({action,...extra})});return {status:r.status,body:await r.json()};},{action,extra});
	const picker=wiki.getByRole("dialog",{name:"选择知识库文件夹"});
	await picker.locator("input").fill(cwd);
	await picker.getByRole("button",{name:"选择知识库文件夹",exact:true}).click();
	await wiki.locator(".wiki-workbench").waitFor();
	assert.equal((await api("read")).body.cwd,cwd);
	await wiki.locator('.wiki-tree-main[title="README.md"]').click();
	await wiki.locator(".wiki-prose .fp-rich-document").waitFor();
	await wiki.waitForFunction(()=>new URL(location.href).searchParams.get("doc")==="README.md");
	for(let i=0;i<40&&(await api("read")).body.path!=="README.md";i++)await new Promise(r=>setTimeout(r,100));
	assert.equal((await api("read")).body.path,"README.md");
	await wiki.close();
	const again=page.waitForEvent("popup");await page.getByRole("button",{name:"知识库",exact:true}).click();const restored=await again;
	await restored.locator(".wiki-prose .fp-rich-document").waitFor();
	assert.equal(new URL(restored.url()).searchParams.get("doc"),"README.md");
	const second = join(base, "second-library"); mkdirSync(second); writeFileSync(join(second,"B.md"),"# Library B\n");
	await restored.getByRole("button",{name:"更换知识库文件夹",exact:true}).click();
	const change=restored.getByRole("dialog",{name:"更换知识库文件夹"});await change.locator("input").fill(second);
	await change.getByRole("button",{name:"更换知识库文件夹",exact:true}).click();await change.waitFor({state:"detached"});
	await restored.waitForFunction(cwd=>new URL(location.href).searchParams.get("cwd")===cwd,second);
	const stored=JSON.parse(readFileSync(join(base,"data/knowledge-library.json"),"utf8"));assert.equal(stored.cwd,second);
	await restored.close();
	rmSync(second,{recursive:true});
	const missingPopup=page.waitForEvent("popup");await page.getByRole("button",{name:"知识库",exact:true}).click();const missing=await missingPopup;
	await missing.getByRole("dialog",{name:"选择知识库文件夹"}).waitFor();
	assert(await missing.getByText("知识库文件夹不可用，请重新选择。").isVisible());await missing.close();
	assert.equal(sent.filter(m=>m.type==="set_cwd").length,0,"library never changes main workspace");
	assert.deepEqual(errors,[]);
	console.log("knowledge-library-browser: PASS");
} catch(error) { console.error(log.slice(-6000)); throw error; }
finally { releaseReply(); await browser?.close(); server.kill("SIGTERM"); await Promise.race([once(server,"exit"),new Promise(r=>setTimeout(r,5000))]); if(server.exitCode===null)server.kill("SIGKILL"); mock.closeAllConnections?.(); await new Promise(r=>mock.close(r)); rmSync(base,{recursive:true,force:true}); }
