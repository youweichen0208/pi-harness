/** Real Jedi completions rendered by CodeMirror; optional existing app tools are read-only. */
import assert from "node:assert/strict";
import { mkdirSync, symlinkSync } from "node:fs";
import { join } from "node:path";
import { chromium } from "playwright-core";
import { CHROME_PATH } from "./lib/chrome.mjs";
import { playgroundFixture } from "./lib/playground-fixture.mjs";
const fixture = await playgroundFixture({ PI_WEB_PYTHON: process.env.PI_WEB_PYTHON });
if (process.env.PI_TEST_PYTHON_TOOLS) symlinkSync(process.env.PI_TEST_PYTHON_TOOLS, join(fixture.dataDir, "python-tools"), "dir");
let browser;
try {
	const invalid = 'def add(a: int, b: int) -> int:\n    a = 1\nb = 2\n    return a + b';
	await fixture.api("scratch", { expectedVersion: (await (await fixture.api("scratch")).json()).updatedAt, content: invalid, tests: { mode: "program", selectedMethod: "", casesByMethod: {} } }, "PUT");
	browser = await chromium.launch({ executablePath: CHROME_PATH || undefined });
	const page = await browser.newPage({ viewport: { width: 1400, height: 900 } });
	await page.goto(`${fixture.base}/?token=${fixture.token}`);
	await page.locator(".setup-modal .modal-close").click();
	await page.getByRole("button", { name: "Playground", exact: true }).click();
	const editor = page.locator('.scratch-editor-cm .cm-content');
	await editor.waitFor();
	await page.getByRole('button', { name: '格式化', exact: true }).click();
	const error = page.locator('.scratch-code-pane [role="alert"]');
	await error.waitFor();
	assert.equal(await editor.innerText(), invalid, 'invalid source remains unchanged');
	assert.equal(await page.locator('.playground-tools-install').count(), 0, 'syntax error must not suggest reinstalling tools');
	assert.match(await error.innerText(), /第 4 行/);
	assert.equal(await error.locator('pre').isVisible(), false, 'traceback is collapsed');
	mkdirSync('tests/scratch', { recursive: true });
	await page.screenshot({ path: 'tests/scratch/playground-format-error.png' });
	await error.locator('summary').click();
	assert.match(await error.locator('pre').innerText(), /Cannot parse/);
	// Save repairs the entire script even when only the return statement is selected.
	assert.equal(await page.getByRole('button', { name: '自动缩进全文', exact: true }).count(), 0);
	await editor.press('ControlOrMeta+End');
	await editor.press('Shift+Home');
	await editor.press('ControlOrMeta+s');
	await page.waitForFunction(() => document.querySelector('.cm-content')?.innerText.includes('\n    b = 2'));
	await page.getByRole('button', { name: '格式化', exact: true }).waitFor();
	await error.waitFor({ state: 'detached' });
	await page.waitForFunction(() => document.querySelector('.scratch-save-status')?.textContent.includes('已保存'));
	assert.equal((await (await fixture.api('scratch')).json()).content.trimEnd(), invalid.replace('\nb = 2', '\n    b = 2'));
	const valid = 'def add(a,b):\n    a=1\n    b=2\n    return a+b';
	await editor.fill(valid);
	await error.waitFor({ state: 'detached' });
	await page.getByRole('button', { name: '格式化', exact: true }).click();
	await page.waitForFunction(() => document.querySelector('.cm-content')?.textContent.includes('return a + b'));
	assert.match(await editor.innerText(), /def add\(a, b\):/);
	await page.route('**/api/playground/format*', route => route.fulfill({ status: 422, contentType: 'application/json', body: JSON.stringify({ error: 'Install black in the selected Python environment.' }) }));
	await page.getByRole('button', { name: '格式化', exact: true }).click();
	await page.locator('.playground-tools-install').waitFor();
	await editor.fill('print(1)');
	await error.waitFor({ state: 'detached' });
	await page.unroute('**/api/playground/format*');
	let pending;
	await page.route('**/api/playground/format*', route => { pending = route; });
	await page.getByRole('button', { name: '格式化', exact: true }).click();
	for (let i = 0; !pending && i < 100; i++) await page.waitForTimeout(20);
	assert(pending);
	await editor.fill('print(2)');
	await pending.fulfill({ status: 422, contentType: 'application/json', body: JSON.stringify({ error: 'Cannot parse: 1:0: old source' }) });
	await page.getByRole('button', { name: '格式化', exact: true }).waitFor();
	assert.equal(await error.count(), 0, 'late format errors cannot attach to newer source');
	assert.equal(await editor.innerText(), 'print(2)');
	await page.unroute('**/api/playground/format*');
	await editor.fill('def broken(:');
	await editor.press('ControlOrMeta+s');
	await page.getByText('无法确定正确的缩进，请检查代码块结构后重试。原代码已保留。', { exact: true }).waitFor();
	await page.waitForFunction(() => document.querySelector('.scratch-save-status')?.textContent.includes('已保存'));
	assert.equal((await (await fixture.api('scratch')).json()).content, 'def broken(:', 'save survives indentation failure');
	await page.route('**/api/playground/format*', route => route.fulfill({ status: 422, contentType: 'application/json', body: JSON.stringify({ error: 'Install black in the selected Python environment.' }) }));
	await editor.fill(invalid);
	await editor.press('ControlOrMeta+s');
	await page.locator('.playground-tools-install').waitFor();
	await page.waitForFunction(() => document.querySelector('.scratch-save-status')?.textContent.includes('已保存'));
	assert.equal((await (await fixture.api('scratch')).json()).content, invalid.replace('\nb = 2', '\n    b = 2'), 'save keeps indentation when Black is unavailable');
	console.log('PASS format syntax error: source preserved, no reinstall prompt, concise line hint, collapsible details, edit clears error and valid format succeeds');
} finally { await browser?.close(); await fixture.stop(); }
