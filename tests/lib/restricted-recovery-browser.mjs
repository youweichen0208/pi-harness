/** Reuses the real SSH fixture and production application from node-agent-test. */
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
export async function exerciseRestrictedRecovery({ page, dataDir, setMode, requestCount }) {
	await page.setViewportSize({ width: 1400, height: 950 });
	page.setDefaultTimeout(15000);
	const node = page.locator('.node-agent'), nodeInput = node.locator('textarea[aria-label="让 Agent 在此节点执行任务…"]');
	await node.locator('.node-agent-input .dropdown').click();
	await node.getByRole('menuitemradio', { name: 'recovery / Recovery fixture', exact: true }).click();
	await node.locator('.node-agent-input .dropdown', { hasText: 'Recovery fixture' }).waitFor();
	await nodeInput.fill('NATIVE_NODE_SEED ' + 'context '.repeat(200)); await nodeInput.press('Enter');
	await node.locator('.node-agent-message.assistant', { hasText: 'Recovery fixture answer' }).waitFor();
	await node.locator('.node-agent-working').waitFor({ state: 'hidden' });
	setMode('retry'); await nodeInput.fill('Trigger native retry'); await nodeInput.press('Enter');
	const retry = node.locator('.agent-silence', { hasText: '等待原生重试' }); await retry.waitFor();
	const first = /([0-9]+)s/.exec(await retry.innerText())?.[1]; assert(first);
	await page.waitForFunction(initial => { const text = document.querySelector('.node-agent .agent-silence')?.textContent ?? ''; const n = /([0-9]+)s/.exec(text)?.[1]; return n && Number(n) < Number(initial); }, first);
	await nodeInput.fill('preserved node draft');
	const count = requestCount(); await retry.getByRole('button', { name: '取消', exact: true }).click();
	await retry.waitFor({ state: 'hidden' }); await node.locator('.node-agent-working').waitFor({ state: 'hidden' });
	assert.equal(requestCount(), count); assert.equal(await nodeInput.inputValue(), 'preserved node draft');
	setMode('hang'); await nodeInput.fill('/compact'); await nodeInput.press('Enter');
	const compact = node.locator('.compaction-status', { hasText: '正在压缩' }); await compact.waitFor();
	await nodeInput.fill('draft survives disconnect');
	await page.evaluate(() => { window.recoveryFixtureOffline = true; window.recoveryFixtureSocket.close(); });
	await page.waitForFunction(() => !document.querySelector('.conn-dot.ok'));
	assert(await node.locator('.compaction-status button').isDisabled(), 'offline compaction cancellation is disabled');
	assert(await nodeInput.isDisabled(), 'SSH agent also requires the browser transport');
	const disconnectedCount = requestCount();
	await page.evaluate(() => { window.recoveryFixtureOffline = false; });
	await page.waitForFunction(() => !!document.querySelector('.conn-dot.ok') && !document.querySelector('.node-agent .compaction-status button')?.disabled);
	assert.equal(requestCount(), disconnectedCount, 'reconnect does not replay model requests');
	assert.equal(await nodeInput.inputValue(), 'draft survives disconnect');
	await compact.getByRole('button', { name: '取消', exact: true }).click();
	await compact.waitFor({ state: 'hidden' }); await node.locator('.node-agent-working').waitFor({ state: 'hidden' });
	// Same-length external change triggers the real native storage guard.
	const directory = join(dataDir, 'omp/sessions/ssh');
	const nodeFile = readdirSync(directory, { recursive: true }).filter(name => name.endsWith('.jsonl')).map(name => join(directory, name)).find(file => readFileSync(file, 'utf8').includes('NATIVE_NODE_SEED'));
	assert(nodeFile); writeFileSync(nodeFile, readFileSync(nodeFile, 'utf8').replace('NATIVE_NODE_SEED', 'EDITED_NODE_SEED'));
	const persistence = node.locator('.session-persistence'); await persistence.waitFor();
	await nodeInput.fill('draft survives reopen');
	assert(await node.getByRole('button', { name: '发送', exact: true }).isDisabled());
	const beforeReopen = requestCount(); setMode('normal');
	await persistence.getByRole('button', { name: '重新读取已保存历史', exact: true }).click(); await persistence.waitFor({ state: 'hidden' });
	assert.equal(requestCount(), beforeReopen); assert.equal(await nodeInput.inputValue(), 'draft survives reopen');
	await node.getByText('EDITED_NODE_SEED', { exact: false }).waitFor();
	await page.getByRole('tab', { name: '对话', exact: true }).click();
	await page.getByRole('button', { name: 'Playground', exact: true }).click();
	await page.getByRole('tab', { name: 'AI助手', exact: true }).click();
	const pg = page.locator('.pg-chat'), input = pg.locator('#pg-chat-input');
	await pg.locator('.input-tools .dropdown > button').first().click();
	await pg.locator('.dd-menu .dd-item', { hasText: 'Recovery fixture' }).click();
	await pg.locator('.chip-model', { hasText: 'Recovery fixture' }).waitFor();
	await input.fill('NATIVE_PG_SEED'); await pg.getByRole('button', { name: '发送', exact: true }).click();
	await pg.getByText('Recovery fixture answer.', { exact: false }).waitFor();
	await pg.getByRole('button', { name: '发送', exact: true }).waitFor();
	setMode('retry'); await input.fill('Retry Playground'); await pg.getByRole('button', { name: '发送', exact: true }).click();
	const pgRetry = pg.locator('.agent-silence', { hasText: '等待原生重试' }); await pgRetry.waitFor();
	await input.fill('preserved Playground draft');
	const beforeCancel = requestCount(); await pgRetry.getByRole('button', { name: '取消', exact: true }).click();
	await pgRetry.waitFor({ state: 'hidden' }); await pg.getByRole('button', { name: '发送', exact: true }).waitFor();
	assert.equal(requestCount(), beforeCancel); assert.equal(await input.inputValue(), 'preserved Playground draft');
	const saved = JSON.parse(readFileSync(join(dataDir, 'omp/playground-chat/state.json'), 'utf8'));
	const file = saved.history.find(entry => entry.id === saved.current).sessionFile;
	writeFileSync(file, readFileSync(file, 'utf8').replace('NATIVE_PG_SEED', 'EDITED_PG_SEED'));
	const pgPersistence = pg.locator('.session-persistence'); await pgPersistence.waitFor();
	assert(await pg.getByRole('button', { name: '发送', exact: true }).isDisabled());
	await page.setViewportSize({ width: 390, height: 844 });
	await page.evaluate(() => { document.documentElement.dataset.appearance = 'dark'; window.dispatchEvent(new Event('pi:theme-change')); });
	assert(await pgPersistence.getByRole('button', { name: '重新读取已保存历史', exact: true }).isVisible());
	const bannerBox = await pgPersistence.boundingBox(), reopenBox = await pgPersistence.getByRole('button', { name: '重新读取已保存历史', exact: true }).boundingBox();
	assert(bannerBox && reopenBox && reopenBox.y + reopenBox.height <= bannerBox.y + bannerBox.height + 1, 'narrow recovery action is not clipped by the banner');
	assert(reopenBox.height >= 44 && reopenBox.x >= 0 && reopenBox.x + reopenBox.width <= 390, 'recovery action remains a visible touch target');
	await pgPersistence.screenshot({ path: 'tests/scratch/omp-restricted-recovery-narrow.png' });
	setMode('normal'); const pgBeforeReopen = requestCount();
	await pgPersistence.getByRole('button', { name: '重新读取已保存历史', exact: true }).click(); await pgPersistence.waitFor({ state: 'hidden' });
	assert.equal(requestCount(), pgBeforeReopen); assert.equal(await input.inputValue(), 'preserved Playground draft');
	await pg.getByText('EDITED_PG_SEED', { exact: true }).waitFor();
	console.log('PASS restricted browser recovery: real native retries, SSH compaction, scoped cancel, countdown, external-history guard/reopen, preserved drafts and narrow layout');
}
