/** Organic handoff: real UI, offline fonts, navigation and responsive surfaces. */
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium } from 'playwright-core';
import { CHROME_PATH } from './lib/chrome.mjs';
import { portUp } from './lib/port-utils.mjs';
const port = 9286, root = mkdtempSync(join(tmpdir(), 'pi-organic-'));
const cwd = join(root, 'organic-workspace'); mkdirSync(cwd);
writeFileSync(join(cwd, 'README.md'), '# Organic workspace\n\n用于阅读、编辑和分析的工作区。\n\n## A calmer workspace\n\nFigtree body text and 中文正文。\n\n```js\nconst workspace = "organic";\n```\n');
let server, browser;
try {
	assert.equal(await portUp(port), false);
	server = spawn(process.execPath, ['dist/server/index.js'], { env: { ...process.env, PORT: String(port), PI_WEB_TOKEN: '', PI_WEB_CWD: cwd, PI_WEB_DATA_DIR: join(root, 'data'), PI_CODING_AGENT_DIR: join(root, 'agent') }, stdio: 'ignore' });
	for (let i = 0; i < 150 && !await portUp(port); i++) await new Promise(r => setTimeout(r, 100));
	assert(await portUp(port));
	browser = await chromium.launch({ executablePath: CHROME_PATH });
	const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
	page.setDefaultTimeout(12000);
	const errors = [], external = [];
	let socket, baseState;
	await page.routeWebSocket('**/ws', route => {
		socket = route; const upstream = route.connectToServer();
		route.onMessage(wire => upstream.send(wire));
		upstream.onMessage(wire => { const message = JSON.parse(wire.toString()); if (message.type === 'snapshot') baseState = message.state; route.send(wire); });
	});
	page.on('pageerror', e => errors.push(e.message));
	await page.route('**/*', route => { if (!route.request().url().startsWith(`http://127.0.0.1:${port}`)) { external.push(route.request().url()); return route.abort(); } return route.continue(); });
	await page.goto(`http://127.0.0.1:${port}`);
	await page.locator('.setup-modal .modal-close').click();
	await page.locator('.sidebar-connection .conn-dot.ok').waitFor();
	await page.locator('.workspace-group-manager input').fill('Studio');
	await page.locator('.workspace-group-actions button[type=submit]').click();
	await page.locator('.workspace-outside button').click();
	await page.locator('.project-item.active').waitFor();
	await page.evaluate(async () => { await document.fonts.load('400 18px Caprasimo'); await document.fonts.load('400 14px Figtree'); await document.fonts.load('600 14px Figtree'); await document.fonts.ready; });
	assert(await page.evaluate(() => ['Caprasimo', 'Figtree'].every(name => [...document.fonts].some(font => font.family.replaceAll('"', '') === name && font.status === 'loaded'))));
	const tokens = await page.evaluate(() => Object.fromEntries(['--bg','--accent','--link','--sidebar-bg','--r-sm','--r-md','--r-lg','--r-waiting','--fs-base'].map(k => [k, getComputedStyle(document.documentElement).getPropertyValue(k).trim()])));
	assert.deepEqual(tokens, {'--bg':'#f5ead8','--accent':'#c67139','--link':'#8c491a','--sidebar-bg':'#ebddc5','--r-sm':'999px','--r-md':'22px','--r-lg':'28px','--r-waiting':'50%','--fs-base':'14.5px'});
	assert.equal(await page.locator('.statusbar').count(), 0);
	assert.deepEqual(await page.locator('.view-switch [role=tab]').allTextContents(), ['对话','终端','Git']);
	assert.equal(await page.locator('.sidebar-brand strong').evaluate(el => getComputedStyle(el).fontFamily.split(',')[0].replaceAll('"','')), 'Caprasimo');
	assert.equal(await page.locator('.panel-left').evaluate(el => getComputedStyle(el).borderTopLeftRadius), '28px');
	assert((await page.locator('.drawer-left').boundingBox()).x >= 9);
	assert((await page.locator('.drawer-right').boundingBox()).y >= 9);
	assert.equal(await page.locator('.inputbox').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(249, 244, 237)');
	assert.equal(await page.locator('.topbar .view-switch svg').first().evaluate(el => getComputedStyle(el).strokeWidth), '2.5px');
	mkdirSync('tests/scratch', { recursive: true });
	await page.locator('.inputbar textarea').fill('Review this workspace');
	await page.screenshot({path:'tests/scratch/organic-chat.png'});
	const more = page.locator('.workspace-more > .dropdown > button');
	await more.click(); await page.locator('.workspace-view-menu').getByRole('button',{name:'数据库',exact:true}).click();
	await page.locator('.database-workbench').waitFor();
	assert.equal(await page.locator('.wiki-agent-chat .inputbar textarea').inputValue(),'Review this workspace');
	await page.locator('.database-actions').getByRole('button',{name:'新建连接',exact:true}).click();
	await page.locator('.database-form').waitFor();
	await page.screenshot({path:'tests/scratch/organic-database.png'});
	await page.locator('.wiki-modal-header > button').last().click();
	await page.locator('.file-name',{hasText:'README.md'}).first().click();
	await page.locator('.wiki-prose .fp-rich-document').waitFor();
	assert.equal(await page.locator('.wiki-document-heading h1').evaluate(el => getComputedStyle(el).fontFamily.split(',')[0].replaceAll('"','')), 'Caprasimo');
	await page.screenshot({path:'tests/scratch/organic-wiki.png'});
	await page.locator('.wiki-modal-header > button').last().click();
	await page.locator('#sidebar-settings-slot .chip').click();
	await page.locator('.workspace-settings-menu').getByRole('button',{name:'所有设置',exact:true}).click();
	await page.locator('.settings-modal').waitFor();
	await page.waitForFunction(() => getComputedStyle(document.querySelector('.settings-modal')).opacity === '1');
	await page.screenshot({path:'tests/scratch/organic-settings.png'});
	await page.keyboard.press('Escape');
	await page.evaluate(() => document.documentElement.dataset.appearance = 'dark');
	await page.waitForTimeout(250);
	await page.screenshot({path:'tests/scratch/organic-dark.png'});
	await page.evaluate(() => document.documentElement.dataset.appearance = 'light');
	await page.setViewportSize({width:390,height:844});
	await page.emulateMedia({reducedMotion:'reduce'});
	await more.click();
	const menu = await page.locator('.workspace-view-menu').boundingBox();
	assert(menu.x >= 0 && menu.x + menu.width <= 390);
	await page.locator('.workspace-view-menu').getByRole('button',{name:'数据库',exact:true}).click();
	await page.locator('.database-workbench').waitFor();
	assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
	await page.screenshot({path:'tests/scratch/organic-mobile.png'});
	await page.locator('.wiki-modal-header > button').last().click();
	await page.locator('.topbar .brand .panel-toggle').click();
	await page.locator('.drawer-left.open .sidebar-connection').waitFor();
	await page.screenshot({path:'tests/scratch/organic-mobile-sidebar.png'});
	await page.setViewportSize({width:1440,height:1000});
	socket.send(JSON.stringify({type:'snapshot',state:{...baseState,isStreaming:true,streamingMessage:null,messages:[{id:'organic-wait',role:'user',content:[{type:'text',text:'Analyze this workspace'}]}]}}));
	await page.locator('.waiting-brand').waitFor();
	const dots = await page.locator('.waiting-brand i').evaluateAll(nodes => nodes.map(el => { const style = getComputedStyle(el); return [style.backgroundColor, style.borderRadius, style.animationName]; }));
	assert.deepEqual(dots, [['rgb(198, 113, 57)','50%','none'],['rgb(122, 138, 94)','50%','none'],['rgb(246, 160, 107)','50%','none']]);
	assert.deepEqual(errors, []); assert.deepEqual(external, []);
	console.log('PASS Organic handoff: tokens, local fonts, Lucide, floating panels, More navigation, same-chat database/Wiki, settings, dark and mobile');
} finally {
	await browser?.close();
	if (server) { server.kill('SIGTERM'); if (server.exitCode === null) await new Promise(r => server.once('exit',r)); }
	rmSync(root,{recursive:true,force:true});
}
