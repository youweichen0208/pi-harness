/** Real OMP project restoration, coalesced navigation and failed-history isolation. */
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdtempSync, mkdirSync, writeFileSync, realpathSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { setTimeout as delay } from 'node:timers/promises';
import { scrubHostEnv } from './lib/test-env.mjs';
import { createOmpHistory } from './lib/omp-history-fixture.mjs';
import { OmpClientSession } from '../dist/server/omp/chat-service.js';
import { OmpPersistenceJournal } from '../dist/server/omp/persistence-journal.js';
import { ClientStateStore } from '../dist/server/client-state.js';

scrubHostEnv();
const root = mkdtempSync(join(tmpdir(), 'omp-workspaces-')), data = join(root, 'data');
const projects = ['a', 'b', 'failed', 'unavailable'].map(name => join(root, name));
const agent = join(data, 'omp', 'agent');
mkdirSync(agent, { recursive: true });
writeFileSync(join(agent, 'config.yml'), JSON.stringify({ skills: { enabled: false }, retry: { enabled: false }, cacheWarming: { enabled: false } }));
for (const cwd of projects) mkdirSync(cwd);
const histories = [];
let client, restored, restoreFetch, releaseUpdate;
try {
	await createOmpHistory({ dataDir: data, cwd: projects[0], messages: [{ role: 'user', content: 'older history', timestamp: Date.now() }] });
	await delay(30);
	for (const [index, cwd] of projects.slice(0, 3).entries()) histories.push(await createOmpHistory({ dataDir: data, cwd, messages: [{ role: 'user', content: `workspace ${index}`, timestamp: Date.now() }] }));
	new OmpPersistenceJournal(join(data, 'omp')).record(histories[2].sessionFile, true);
	const catalog = join(data, 'omp', 'sessions', 'chat', createHash('sha256').update(realpathSync(projects[3])).digest('hex').slice(0, 24));
	writeFileSync(catalog, 'not a directory');
	const messages = [], store = new ClientStateStore(join(data, 'client-state.json'));
	client = new OmpClientSession('workspace-test', projects[0], store);
	client.attachSink(message => messages.push(message), false);
	await client.initialize();
	assert.equal(client.session.state.sessionFile, histories[0].sessionFile, 'startup restores newest native history');
	await client.pushProjects();
	const discovered = messages.findLast(message => message.type === 'projects').projects;
	assert(discovered.some(project => project.path === projects[0]), 'saved display path remains stable');
	assert.equal(new Set(discovered.map(project => realpathSync(project.path))).size, discovered.length, 'canonical native paths must not duplicate saved workspace aliases');
	store.removeProject('workspace-test', projects[0]);
	await client.pushProjects();
	assert(!messages.findLast(message => message.type === 'projects').projects.some(project => realpathSync(project.path) === realpathSync(projects[0])), 'removal hides the canonical disk alias too');
	await client.setCwd(projects[0]); await client.pushProjects();
	assert(messages.findLast(message => message.type === 'projects').projects.some(project => project.path === projects[0]), 'explicit reopening restores the saved alias');
	const original = client.conversationId;
	await client.newChat(true);
	assert.notEqual(client.conversationId, original);
	await client.switchConversation(original);

	const offset = messages.length;
	await Promise.all(Array.from({ length: 12 }, (_, index) => client.setCwd(projects[index === 0 || index === 11 ? 1 : 2], `rapid-${index}`)));
	const results = messages.slice(offset).filter(m => m.type === 'cwd_result');
	assert.equal(results.length, 12);
	assert.equal(results.at(-1).requestId, 'rapid-11');
	assert.equal(results.at(-1).ok, true);
	assert(results.some(m => m.error === 'superseded'));
	assert(!messages.slice(offset).some(m => (m.type === 'snapshot' || m.type === 'snapshot_delta') && m.state.cwd === projects[2]), 'superseded target never becomes authoritative');
	assert.equal(client.session.state.sessionFile, histories[1].sessionFile);
	await client.setCwd(projects[0], 'back');
	assert.equal(client.conversationId, original, 'return to most recently selected conversation, not newest-created blank');
	assert.deepEqual(client.session.state.cwdEvents, [], 'UI navigation does not append native workspace events');
	const modelContext = (await client.session.command('get_messages')).data.messages;
	await client.setCwd(projects[1], 'command-b', 'command');
	assert.equal(client.session.state.cwdEvents.length, 1);
	await client.setCwd(projects[0], 'command-a', 'command');
	const cwdEvents = structuredClone(client.session.state.cwdEvents);
	assert.equal(cwdEvents.length, 1, 'other project events never leak into this conversation');
	assert.equal(cwdEvents[0].cwd, realpathSync(projects[0]));
	assert.deepEqual((await client.session.command('get_messages')).data.messages, modelContext, 'workspace metadata never changes the native model context');
	await client.session.stop();
	await client.session.open();
	assert.deepEqual(client.session.state.cwdEvents, cwdEvents, 'native events survive stopping and reopening the worker');

	const beforeFailure = messages.length;
	await client.setCwd(projects[3], 'catalog-failure');
	assert.equal(messages.find(m => m.requestId === 'catalog-failure').ok, false);
	assert.equal(client.conversationId, original);
	assert.deepEqual(client.session.state.cwdEvents, cwdEvents, 'failed workspace preparation does not append an event');
	assert(messages.slice(beforeFailure).filter(m => (m.type === 'snapshot' || m.type === 'snapshot_delta')).every(m => m.state.conversationId === original), 'failed preparation never publishes a new active conversation');
	await client.setCwd(projects[2], 'failed-history');
	assert.equal(client.session.state.sessionFile, histories[2].sessionFile);
	assert.equal(client.session.state.persistence?.failed, true, 'automatic project restoration preserves the recovery restriction');
	assert.equal(client.session.generation, undefined, 'failed history never starts a worker');
	await assert.rejects(client.session.open(), /保存失败|recovery|历史|persist/i);
	await client.setCwd(projects[0], 'healthy');
	assert.equal(client.conversationId, original);
	assert(!client.session.state.persistence?.failed, 'another project remains usable');
	await client.dispose(); client = undefined;

	restored = new OmpClientSession('workspace-test', projects[0], store);
	await restored.initialize();
	assert.equal(restored.session.state.sessionFile, histories[0].sessionFile, 'saved selection wins over the more recently created empty history');
	assert.deepEqual(restored.session.state.cwdEvents, cwdEvents, 'native events survive client disposal and restoration');
	assert.deepEqual((await restored.session.command('get_messages')).data.messages, modelContext, 'restored events remain outside model context');
	await restored.session.newSession();
	assert.deepEqual(restored.session.state.cwdEvents, [], 'native new_session clears outgoing workspace events');
	await restored.pushProjects();
	assert.equal(restored.canEvict, true, 'disconnected idle history is available for another window');
	const passiveRead = restored.pushProjects();
	assert.equal(restored.canEvict, true, 'a passive project catalog read must not block history handoff');
	await passiveRead;
	const originalFetch = globalThis.fetch;
	let updateSignal;
	restoreFetch = () => { globalThis.fetch = originalFetch; };
	globalThis.fetch = async (url, options) => {
		assert.equal(url, 'https://registry.npmjs.org/@youweichen%2fpi-harness/latest');
		updateSignal = options.signal;
		return new Promise((resolve, reject) => {
			releaseUpdate = () => resolve(Response.json({ version: '0.0.0' }));
			options.signal.addEventListener('abort', () => reject(options.signal.reason), { once: true });
		});
	};
	const update = restored.handle({ type: 'check_update' });
	assert(updateSignal, 'the version lookup is actually in flight');
	assert.equal(restored.canEvict, true, 'a passive app version lookup must not block history handoff');
	await restored.dispose(); restored = undefined;
	assert.equal(updateSignal.aborted, true, 'disposing the old client cancels its passive network request');
	await update;
	console.log('PASS OMP workspaces: native latest history, explicit saved selection, coalesced acknowledgements, active-chat recency, transactional failure and recovery isolation');
} finally {
	restoreFetch?.(); releaseUpdate?.();
	await client?.dispose(); await restored?.dispose();
	rmSync(root, { recursive: true, force: true });
}
