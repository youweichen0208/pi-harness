import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { CHROME_PATH } from './lib/chrome.mjs';
import { playgroundFixture } from './lib/playground-fixture.mjs';
const fixture = await playgroundFixture();
let browser;
try {
	browser = await chromium.launch({executablePath: CHROME_PATH});
	const page = await browser.newPage({viewport:{width:1440,height:900}});
	let base, socket;
	const stamp=Date.now();
	const steps=[{id:'cmd',messageId:'command',title:'运行工具',status:'done',startedAt:stamp-2000,endedAt:stamp-1000,artifacts:[{toolCallId:'cmd',kind:'bash',label:'pwd'}]},{id:'edit',messageId:'edit',title:'修改文件',status:'running',startedAt:stamp,artifacts:[{toolCallId:'edit',kind:'edit',label:'修改 example.ts',path:'example.ts'}]}];
	const send=()=>socket.send(JSON.stringify({type:'snapshot',state:{...base,piConfigured:true,isStreaming:true,messages:[],streamingMessage:null,taskProgress:{id:'fixture',conversationId:base.conversationId,sourceMessageId:'question',title:'优化面板',status:'running',startedAt:stamp-2000,completed:1,steps}}}));
	await page.routeWebSocket(/\/ws(?:\?|$)/,route=>{socket=route;const upstream=route.connectToServer();route.onMessage(w=>upstream.send(w));upstream.onMessage(w=>{const m=JSON.parse(String(w));if(m.type==='snapshot'||m.type==='snapshot_delta'){base={...base,...m.state};send();}else route.send(w);});});
	await page.goto(`${fixture.base}/?token=${fixture.token}`);

	await page.locator('.right-panel-tabs').waitFor();
	assert.equal(await page.locator('.right-panel-tabs [aria-selected="true"]').textContent(), '文件');
	assert.equal(await page.locator('.task-sections').isVisible(), false);
	await page.waitForFunction(() => !!document.querySelector('.tree-root')?.getAttribute('title'));
	await page.locator('.tree-root').click();
	assert.equal(await page.locator('.tree-root').locator('..').getAttribute('aria-expanded'), 'false');
	await page.locator('.header-task-progress').click();
	assert.equal(await page.locator('.header-task-segments i').count(), 2);
	const panel=page.locator('.task-sections');
	await panel.waitFor();
	const row=panel.locator('.task-step.running');
	await row.waitFor();
	const colors=await row.evaluate(el=>{const s=getComputedStyle(el);const root=getComputedStyle(document.documentElement);const sample=document.createElement('span');sample.style.color='var(--text)';el.append(sample);const text=getComputedStyle(sample).color;sample.remove();return {border:s.borderLeftWidth,background:s.backgroundColor,title:getComputedStyle(el.querySelector('.task-step-title')).color,text,animation:getComputedStyle(el.querySelector('.task-step-spinner')).animationName};});
	assert.equal(colors.border,'4px');assert.equal(colors.title,colors.text);assert.equal(colors.animation,'spin');
	assert.equal(await row.locator('.thinking-spinner').count(),0);
	await page.screenshot({path:'tests/scratch/hermes-redesign-light.png'});
	await row.locator('.task-step-toggle').click();
	await row.locator('.task-step-items').waitFor();
	assert.match(await row.innerText(),/example.ts/);
	await row.locator('.task-step-toggle').press('Enter');
	assert.equal(await row.locator('.task-step-items').count(),0);
	const tabs = page.locator('.right-panel-tabs [role="tab"]');
	await tabs.nth(1).focus(); await page.keyboard.press('ArrowLeft');
	assert.equal(await tabs.first().getAttribute('aria-selected'), 'true');
	assert.equal(await page.locator('.tree-root').locator('..').getAttribute('aria-expanded'), 'false', 'tree state survives tab switch');
	await page.keyboard.press('End');
	await panel.waitFor();
	await page.emulateMedia({reducedMotion:'reduce'});
	assert.equal(await row.locator('.task-step-spinner').evaluate(el=>getComputedStyle(el).animationName),'none');
	await page.evaluate(()=>document.documentElement.setAttribute('data-appearance','dark'));
	await page.screenshot({path:'tests/scratch/hermes-redesign-dark.png'});
	steps[1].status='failed';send();await panel.locator('.task-step.failed').waitFor();
	assert.equal(await panel.locator('.task-step-spinner').count(),0);
	await panel.screenshot({path:'tests/scratch/task-panel-failed.png'});
	await page.setViewportSize({width:390,height:844}); await page.waitForTimeout(400);
	assert(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth + 1));
	await page.screenshot({path:'tests/scratch/hermes-redesign-mobile.png'});
	console.log('PASS Hermes redesign: tabs preserve tree state, task navigation, active row, reduced motion, dark and mobile');
} finally {await browser?.close();await fixture.stop();}
