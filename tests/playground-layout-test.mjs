// Real Python runs and editor interactions; no model calls.
import assert from "node:assert/strict";
import { mkdirSync } from "node:fs";
import { chromium } from "playwright-core";
import { CHROME_PATH } from "./lib/chrome.mjs";
import { playgroundFixture } from "./lib/playground-fixture.mjs";
const fixture = await playgroundFixture();
let browser;
try {
	await fixture.api("config", { enabled: true });
	await fixture.api("scratch", { expectedVersion: (await (await fixture.api("scratch")).json()).updatedAt, content: 'print(1 / 0)', tests: { mode: "program", selectedMethod: "", casesByMethod: {} } }, "PUT");
	browser = await chromium.launch({ executablePath: CHROME_PATH || undefined });
	const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
	const errors = [];
	page.on("pageerror", e => errors.push(e.message));
	await page.goto(`${fixture.base}/?token=${fixture.token}`);
	await page.locator(".setup-modal .modal-close").click();
	await page.getByRole("button", { name: "Playground", exact: true }).click();
	const editor = page.locator('.scratch-editor-cm .cm-content');
	await editor.waitFor();
	await page.getByRole("tab", { name: "输出", exact: true }).click();
	await page.locator(".lc-result-empty").waitFor();
	mkdirSync("tests/scratch", { recursive: true });
	await page.waitForTimeout(200);
	await page.screenshot({ path: "tests/scratch/playground-empty.png" });
	assert.equal(await page.locator(".scratch-head button").count(), 1);
	assert.equal(await page.locator(".scratch-head kbd").count(), 0);
	assert(await page.locator("#scratch-results").isVisible(), "results stay available through tabs");
	await editor.press('ControlOrMeta+Enter');
	await page.locator('.scratch-output .method-validation').filter({ hasText: 'ZeroDivisionError' }).waitFor();
	assert(await page.locator('#scratch-results').isVisible(), "running keeps results visible");
	await page.waitForTimeout(200);
	await page.screenshot({ path: "tests/scratch/playground-error.png" });
	await editor.fill('print("layout passed")\n');
	await editor.press('ControlOrMeta+End');
	await page.waitForFunction(() => document.querySelector('.scratch-code-foot')?.textContent.includes('Ln 2, Col 1'));
	await page.locator('.lc-result-summary').getByText('上次结果', { exact: true }).waitFor();
	await editor.press('ControlOrMeta+Enter');
	await page.locator('.playground-stream pre').filter({ hasText: 'layout passed' }).waitFor();
	assert.match(await page.locator('.playground-stream pre').innerText(), /layout passed/);
	await page.setViewportSize({ width: 390, height: 844 });
	await page.waitForTimeout(200);
	assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
	const mobileCode = await page.locator('.scratch-code-pane').boundingBox();
	const mobileResults = await page.locator('.scratch-test-pane').boundingBox();
	assert(mobileResults.y >= mobileCode.y + mobileCode.height, "narrow layout stacks results below code");
	await page.waitForTimeout(200);
	await page.screenshot({ path: "tests/scratch/playground-mobile.png" });
	await page.evaluate(() => localStorage.setItem("pi-harness:lang", "en"));
	await page.setViewportSize({ width: 1600, height: 1000 });
	await page.reload();
	await page.locator(".setup-modal .modal-close").click();
	await page.getByRole("button", { name: "Playground", exact: true }).click();
	await editor.waitFor();
	await page.evaluate(() => { document.documentElement.setAttribute('data-appearance', 'dark'); window.dispatchEvent(new Event('pi-harness:theme-change')); });
	await page.setViewportSize({ width: 1600, height: 1000 });
	await page.locator('#pg-result-tab').click();
	await page.locator('.lc-result-empty').waitFor();
	await page.waitForTimeout(200);
	await page.screenshot({ path: "tests/scratch/playground-dark-en.png" });
	assert.deepEqual(errors, []);
	console.log("PASS Playground layout: empty/error/success, persistent results, keyboard run, cursor, stale results, mobile, English and dark");
} finally { await browser?.close(); await fixture.stop(); }
